    def validate_authentication(self):
        """
        Valida que los campos de autenticación estén completos y actualiza el estado de la interfaz
        """
        try:
            # Verificar si hay archivos seleccionados
            ortoimagen_path = self.lineEdit.text().strip() if hasattr(self, 'lineEdit') and self.lineEdit.text() else ''
            lotes_path = self.lineEdit_2.text().strip() if hasattr(self, 'lineEdit_2') and self.lineEdit_2.text() else ''
            files_selected = bool(ortoimagen_path and lotes_path)
            
            logger.info(f"Validación - Archivos seleccionados: {files_selected} (Ortoimagen: {bool(ortoimagen_path)}, Lotes: {bool(lotes_path)})")
            logger.info(f"Validación - Autenticado: {self.is_authenticated}")
            
            # Verificar si hay un lote seleccionado en el canvas
            lot_selected = False
            try:
                if lotes_path:
                    # Normalizar rutas para comparación
                    import os
                    lotes_path_normalized = os.path.normpath(os.path.abspath(lotes_path)).lower()
                    
                    for layer in self.iface.mapCanvas().layers():
                        if isinstance(layer, QgsVectorLayer):
                            layer_source = os.path.normpath(os.path.abspath(layer.source())).lower()
                            # Comparar rutas normalizadas
                            if lotes_path_normalized in layer_source or layer_source in lotes_path_normalized:
                                selected_features = layer.selectedFeatures()
                                if selected_features:
                                    lot_selected = True
                                    logger.info(f"Lote seleccionado encontrado en capa: {layer.name()}, FID: {selected_features[0].id()}")
                                break
            except Exception as e:
                logger.warning(f"Error al verificar selección de lote: {str(e)}")
            
            logger.info(f"Validación - Lote seleccionado: {lot_selected}")

            lot_name_filled = bool(self.lotNameEdit.text().strip()) if hasattr(self, 'lotNameEdit') else True
            # Sin carpeta de resultados no hay dónde guardar, así que no se deja
            # generar nada: antes se caía a la carpeta temporal y el usuario
            # perdía de vista dónde habían quedado sus archivos.
            folder_selected = self.tiene_carpeta_de_resultados()

            # Habilitar/deshabilitar el botón OK basado en la autenticación
            if hasattr(self, 'buttonBox'):
                ok_button = self.buttonBox.button(QtWidgets.QDialogButtonBox.Ok)
                if ok_button:
                    should_enable = (self.is_authenticated and files_selected and lot_selected
                                     and lot_name_filled and folder_selected)
                    ok_button.setEnabled(should_enable)
                    logger.info(f"Botón OK {'HABILITADO' if should_enable else 'DESHABILITADO'}")

                    # Si está deshabilitado, mostrar razón en el log
                    if not should_enable:
                        reasons = []
                        if not self.is_authenticated:
                            reasons.append("no autenticado")
                        if not folder_selected:
                            reasons.append("falta carpeta de resultados")
                        if not lot_name_filled:
                            reasons.append("falta nombre del lote")
                        if not files_selected:
                            reasons.append("archivos no seleccionados")
                        if not lot_selected:
                            reasons.append("lote no seleccionado en el canvas")
                        logger.info(f"Razón de deshabilitación: {', '.join(reasons)}")
            
            return self.is_authenticated
            
        except Exception as e:
            logger.error(f"Error al validar autenticación: {str(e)}")
            return False
    
    def _cleanup_saved_state(self):
        """
        Limpia variables guardadas de sesiones anteriores para evitar conflictos.
        Esto es especialmente importante al actualizar el plugin, ya que puede haber
        datos antiguos que causen resultados erróneos.
        """
        try:
            # Limpiar variables de instancia relacionadas con lotes procesados
            if hasattr(self, '_saved_lotes_path'):
                delattr(self, '_saved_lotes_path')
            
            if hasattr(self, 'saved_lot_polygon'):
                delattr(self, 'saved_lot_polygon')
            
            if hasattr(self, 'saved_lot_layer'):
                # Intentar eliminar la capa temporal si existe
                try:
                    if self.saved_lot_layer:
                        QgsProject.instance().removeMapLayer(self.saved_lot_layer.id())
                except:
                    pass
                delattr(self, 'saved_lot_layer')
            
            if hasattr(self, 'saved_azimuth'):
                delattr(self, 'saved_azimuth')
            
            if hasattr(self, 'lot_id'):
                # No eliminar lot_id, solo asegurar que esté en None
                self.lot_id = None
            
            logger.info("Estado guardado limpiado correctamente")
            
        except Exception as e:
            logger.warning(f"Error al limpiar estado guardado (no crítico): {str(e)}")
    
    def save_credentials(self):
        """
        Guarda las credenciales de forma persistente (manteniendo los valores pero enmascarados)
        """
        try:
            settings = QSettings()

            # Solo guardar que existen credenciales, no los valores reales
            document = self.auth_credentials.get('document', '').strip()
            credential = self.auth_credentials.get('credential', '').strip()
            
            if document and credential:
                # Guardar indicadores de que hay credenciales (para mantener campos llenos con asteriscos)
                settings.setValue("detector_palmas/auth/has_document", True)
                settings.setValue("detector_palmas/auth/has_credential", True)
                # Guardar los valores reales para la sesión actual
                settings.setValue("detector_palmas/auth/document", document)
                settings.setValue("detector_palmas/auth/credential", credential)
            else:
                settings.setValue("detector_palmas/auth/has_document", False)
                settings.setValue("detector_palmas/auth/has_credential", False)
                settings.remove("detector_palmas/auth/document")
                settings.remove("detector_palmas/auth/credential")
            
            logger.info("Credenciales guardadas para la sesión")
            
        except Exception as e:
            logger.error(f"Error al guardar credenciales: {str(e)}")
    
    def load_saved_credentials(self):
        """
        Carga las credenciales guardadas de la sesión anterior
        """
        try:
            settings = QSettings()

            # Cargar indicadores de credenciales existentes
            has_document = settings.value("detector_palmas/auth/has_document", False, type=bool)
            has_credential = settings.value("detector_palmas/auth/has_credential", False, type=bool)
            
            if has_document and has_credential:
                # Cargar valores reales si existen
                document = settings.value("detector_palmas/auth/document", "")
                credential = settings.value("detector_palmas/auth/credential", "")
                
                if document and credential:
                    # Mostrar campos con asteriscos pero mantener valores reales internamente
                    self.documentLineEdit.setText("*" * min(len(document), 12))
                    self.credentialLineEdit.setText("*" * min(len(credential), 12))
                    
                    # Guardar valores reales internamente
                    self.auth_credentials['document'] = document
                    self.auth_credentials['credential'] = credential

                    logger.info("Credenciales de sesión anterior cargadas")
            
        except Exception as e:
            logger.error(f"Error al cargar credenciales guardadas: {str(e)}")
    
