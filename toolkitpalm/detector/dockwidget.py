def _normalize_layer_source_path(source_str):
    """Convierte layer.source() en una ruta de archivo válida (sin file:///, sin opciones |...)."""
    if not source_str or not isinstance(source_str, str):
        return source_str or ""
    s = source_str.strip()
    # Quitar opciones de QGIS después de |
    if "|" in s:
        s = s.split("|")[0].strip()
    # Quitar prefijos URI
    for prefix in ("file:///", "file://", "file:"):
        if s.lower().startswith(prefix):
            s = s[len(prefix):].strip()
            break
    return os.path.normpath(s) if s else source_str


