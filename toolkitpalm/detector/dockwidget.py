# Sistema de logging simple y directo a archivo (sin usar logging de Python)
def write_log(message):
    """Escribe directamente a un archivo de log sin usar el sistema de logging"""
    try:
        import datetime
        import os
        timestamp = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        # Usar ruta absoluta para asegurar que se escriba
        log_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'plugin_debug.log')
        log_path = os.path.abspath(log_path)
        with open(log_path, 'a', encoding='utf-8') as f:
            f.write(f"{timestamp} - {message}\n")
            f.flush()  # Forzar escritura inmediata
    except Exception as e:
        # Escribir error a un archivo de error si es posible
        try:
            with open('plugin_error.log', 'a', encoding='utf-8') as f:
                f.write(f"Error en write_log: {str(e)}\n")
        except:
            pass

