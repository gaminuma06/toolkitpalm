    def get_latest_palm_layer(self):
        """
        Capa de palmas sobre la que se trabaja: la elegida en el desplegable si hay
        una, y si no, la más reciente (comportamiento anterior).
        """
        try:
            elegida = self._capa_de_palmas_elegida()
            if elegida is not None:
                return elegida
        except Exception as e:
            logger.warning(f"No se pudo leer la capa elegida en el selector: {e}")
        try:
            # Si tenemos el nombre guardado, buscar esa capa específica
            if self.detected_palm_layer_name:
                logger.info(f"Buscando capa específica: {self.detected_palm_layer_name}")
                for layer in self.iface.mapCanvas().layers():
                    if isinstance(layer, QgsVectorLayer) and layer.name() == self.detected_palm_layer_name:
                        logger.info(f"Capa encontrada: {layer.name()}")
                        return layer
                logger.warning(f"No se encontró la capa guardada: {self.detected_palm_layer_name}")
            
            # Fallback: buscar capas palmas_* o detector_palmas_FID* (nombre único por ejecución)
            palm_layers = []
            for layer in self.iface.mapCanvas().layers():
                if not isinstance(layer, QgsVectorLayer):
                    continue
                name = layer.name()
                if name.startswith('palmas_') or name.startswith('detector_palmas_FID'):
                    palm_layers.append(layer)
            
            if not palm_layers:
                logger.warning("No se encontraron capas de palmas")
                return None
            
            # Ordenar por nombre (detector_palmas_FID32_20260209165000 > ...09164410; palmas_* al final)
            palm_layers.sort(key=lambda x: x.name(), reverse=True)
            logger.info(f"Usando capa de fallback: {palm_layers[0].name()}")
            return palm_layers[0]
            
        except Exception as e:
            logger.error(f"Error al obtener capa de palmas: {str(e)}")
            return None

