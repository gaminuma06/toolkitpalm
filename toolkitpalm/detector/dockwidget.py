                        #         widget.hide()  # COMENTADO PARA COMMIT
                        #         logger.info(f"Botón encontrado y ocultado: {widget.text()}")  # COMENTADO PARA COMMIT
                        
                        
                        # Guardar el nombre de la capa de palmas detectada para el zoom (no sobrescribir si ya es único)
                        logger.info(f"=== VERIFICANDO lot_id: {getattr(self, 'lot_id', 'None')} ===")
                        if hasattr(self, 'lot_id') and self.lot_id is not None and not self.detected_palm_layer_name:
                            self.detected_palm_layer_name = f"palmas_{self.lot_id}"
                            logger.info(f"Nombre de capa de palmas guardado: {self.detected_palm_layer_name}")
                            
