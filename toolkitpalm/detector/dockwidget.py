    def _cargar_imagen(self, nombre_base):
        """Busca la ilustración del paso en la carpeta 'instructivo'.

        Un .gif se reproduce en bucle; png/jpg se muestran escalados. Si no hay
        archivo, queda el recuadro indicando cuál falta -- así el instructivo
        funciona igual mientras se van agregando las imágenes."""
        from qgis.PyQt.QtGui import QPixmap, QMovie

        if self._movie is not None:
            self._movie.stop()
            self._movie = None
        self._ruta_imagen_actual = None

        from .. import recursos_remotos

        carpeta = os.path.join(os.path.dirname(os.path.abspath(__file__)), "instructivo")
        ancho_disponible = max(self._imagen.width(), 480)
        alto_disponible = self._imagen.maximumHeight()
        for extension in (".gif", ".png", ".jpg", ".jpeg"):
            # Primero como estaba: el archivo junto al código (así sigue
            # funcionando en desarrollo). Si no está, la copia ya descargada.
            ruta = os.path.join(carpeta, nombre_base + extension)
            if not os.path.exists(ruta):
                ruta = recursos_remotos.ruta_en_cache(nombre_base + extension)
            if not ruta:
                continue
            self._ruta_imagen_actual = ruta
            if extension == ".gif":
                # Sin esto, el gif se dibuja a su tamaño nativo dentro de una
                # etiqueta más baja: en vez de achicarse, la parte de abajo
                # queda tapada. Se calcula el tamaño real del gif y se escala
                # hacia abajo conservando la proporción.
                self._movie = QMovie(ruta)
                self._movie.jumpToFrame(0)
                nativo = self._movie.currentPixmap().size()
                if nativo.width() and nativo.height():
                    objetivo = nativo.scaled(ancho_disponible, alto_disponible, Qt.KeepAspectRatio)
                    self._movie.setScaledSize(objetivo)
                self._imagen.setMovie(self._movie)
                self._movie.start()
            else:
                pixmap = QPixmap(ruta)
                if not pixmap.isNull():
                    self._imagen.setPixmap(pixmap.scaled(
                        ancho_disponible, alto_disponible,
                        Qt.KeepAspectRatio, Qt.SmoothTransformation
                    ))
            self._imagen.setText("")
            return

        # No está ni junto al código ni descargada: se pide en segundo plano y,
        # cuando llegue, se vuelve a cargar el paso. El instructivo se puede
        # seguir leyendo mientras tanto.
        self._imagen.setMovie(None)
        self._imagen.setPixmap(QPixmap())
        self._imagen.setText("Cargando la ilustración de este paso…")
        self._descargar_ilustracion(nombre_base)

    def _descargar_ilustracion(self, nombre_base):
        """Baja la ilustración que falta, sin bloquear la ventana."""
        from .. import recursos_remotos

        anterior = getattr(self, "_descarga", None)
        if anterior is not None and anterior.isRunning():
            return  # ya hay una en curso; se evita apilar descargas

        self._descarga = recursos_remotos.DescargaRecurso(nombre_base + ".gif", self)
        self._descarga.listo.connect(
            lambda ruta, base=nombre_base: self._on_ilustracion_lista(ruta, base))
        self._descarga.start()

    def _on_ilustracion_lista(self, ruta, nombre_base):
        if ruta:
            self._cargar_imagen(nombre_base)
            return
        self._imagen.setText(
            "(sin ilustración)\n\nNo se pudo descargar la imagen de este paso.\n"
            "Revisa tu conexión: el texto de la guía funciona igual."
        )


