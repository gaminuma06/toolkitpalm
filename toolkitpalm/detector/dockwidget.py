        raiz.appendChild(regla_normal)

        self._deviation_previous_renderer = layer.renderer().clone()
        self._deviation_highlight_layer_id = layer.id()
        layer.setRenderer(QgsRuleBasedRenderer(raiz))
        layer.triggerRepaint()
        self.iface.mapCanvas().refreshAllLayers()

