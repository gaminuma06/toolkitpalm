    def calculate_palm_distance(self):
        """
        Calcula la distancia promedio entre palmas detectadas usando un buffer de 50m
        alrededor del centroide del lote para seleccionar palmas adyacentes.
        """
        from qgis.core import QgsVectorLayer, QgsGeometry, QgsPointXY, QgsCoordinateTransform, QgsProject, QgsCoordinateReferenceSystem
        
        try:
            logger.info("=== INICIANDO CÁLCULO DE DISTANCIA CON BUFFER ===")
            
            # Obtener la capa de palmas
            palm_layer = self.get_latest_palm_layer()
            if not palm_layer:
                logger.error("ERROR: No se encontró capa de palmas")
                return None
            
            logger.info(f"Capa de palmas encontrada: {palm_layer.name()}")
            total_features = palm_layer.featureCount()
            logger.info(f"Features totales en capa de palmas: {total_features}")
            
            # Obtener el polígono del lote
            lot_polygon = None
            lot_crs = None
            
            # Intentar obtener desde la capa de lotes
            lotes_path = getattr(self, '_saved_lotes_path', None) or (self.lineEdit_2.text() if hasattr(self, 'lineEdit_2') else '')
            
            if lotes_path:
                # Buscar la capa de lotes
                for layer in self.iface.mapCanvas().layers():
                    if isinstance(layer, QgsVectorLayer) and layer.source().lower() == lotes_path.lower():
                        if hasattr(self, 'lot_id') and self.lot_id:
                            try:
                                feature = layer.getFeature(int(self.lot_id))
                                if feature.isValid():
                                    geom = feature.geometry()
                                    if geom and not geom.isEmpty():
                                        lot_polygon = QgsGeometry(geom)
                                        if not lot_polygon.isValid():
                                            lot_polygon = lot_polygon.makeValid()
                                        lot_crs = layer.crs()
                                        logger.info(f"Polígono obtenido de capa: {layer.name()}")
                                        break
                            except Exception as e:
                                logger.warning(f"Error al obtener feature: {str(e)}")
            
            # Si no se encontró desde la ruta, buscar en todas las capas
            if not lot_polygon:
                for layer in self.iface.mapCanvas().layers():
                    if isinstance(layer, QgsVectorLayer) and layer.geometryType() == 2:  # Polygon
                        if hasattr(self, 'lot_id') and self.lot_id:
                            try:
                                feature = layer.getFeature(int(self.lot_id))
                                if feature.isValid():
                                    geom = feature.geometry()
                                    if geom and geom.type() == 2 and not geom.isEmpty():
                                        lot_polygon = QgsGeometry(geom)
                                        if not lot_polygon.isValid():
                                            lot_polygon = lot_polygon.makeValid()
                                        lot_crs = layer.crs()
                                        logger.info(f"Polígono encontrado en capa: {layer.name()}")
                                        break
                            except Exception as e:
                                logger.warning(f"Error al obtener feature de {layer.name()}: {str(e)}")
                                continue
            
            if not lot_polygon:
                logger.warning("No se pudo obtener el polígono del lote, usando método alternativo")
                # Fallback: usar las primeras 100 palmas como antes
                max_features = min(100, total_features)
                features = list(palm_layer.getFeatures())[:max_features]
                logger.info(f"Usando método alternativo: {len(features)} features")
            else:
                try:
                    # Calcular centroide del polígono
                    centroid_geom = lot_polygon.centroid()
                    if centroid_geom.isEmpty():
                        raise Exception("Centroide vacío")
                    
                    centroid = centroid_geom.asPoint()
                    logger.info(f"Centroide del lote: {centroid.x():.2f}, {centroid.y():.2f}")
                    
                    # Obtener CRS de la capa de palmas
                    palm_crs = palm_layer.crs()
                    
                    # Crear buffer de 50 metros alrededor del centroide
                    buffer_distance = 50.0  # 50 metros
                    
                    # Crear punto del centroide en el CRS del polígono
                    centroid_point = QgsPointXY(centroid.x(), centroid.y())
                    
                    # Determinar el CRS para crear el buffer (debe ser proyectado)
                    buffer_crs = None
                    centroid_for_buffer = centroid_point
                    
                    # Si el CRS del polígono es proyectado, usarlo
                    if lot_crs and lot_crs.isValid() and lot_crs.isGeographic() == False:
                        buffer_crs = lot_crs
                    # Si el CRS de la capa de palmas es proyectado, usarlo
                    elif palm_crs and palm_crs.isValid() and palm_crs.isGeographic() == False:
                        buffer_crs = palm_crs
                        # Transformar centroide al CRS de la capa de palmas
                        if lot_crs and lot_crs != palm_crs:
                            try:
                                transform = QgsCoordinateTransform(lot_crs, palm_crs, QgsProject.instance())
                                centroid_transformed = transform.transform(centroid_point.x(), centroid_point.y())
                                centroid_for_buffer = QgsPointXY(centroid_transformed.x(), centroid_transformed.y())
                            except Exception as e:
                                logger.warning(f"Error transformando centroide: {str(e)}")
                                raise Exception(f"No se pudo transformar centroide: {str(e)}")
                    else:
                        # Si ninguno es proyectado, usar UTM basado en el centroide
                        logger.warning("Ningún CRS proyectado encontrado, usando UTM")
                        # Calcular zona UTM aproximada (asumiendo que estamos en Colombia, zona 18N)
                        utm_crs = QgsCoordinateReferenceSystem("EPSG:32618")  # UTM 18N
                        buffer_crs = utm_crs
                        # Transformar centroide a UTM
                        if lot_crs:
                            try:
                                transform = QgsCoordinateTransform(lot_crs, utm_crs, QgsProject.instance())
                                centroid_transformed = transform.transform(centroid_point.x(), centroid_point.y())
                                centroid_for_buffer = QgsPointXY(centroid_transformed.x(), centroid_transformed.y())
                                logger.info(f"Centroide transformado a UTM: {centroid_for_buffer.x():.2f}, {centroid_for_buffer.y():.2f}")
                            except Exception as e:
                                logger.warning(f"Error transformando a UTM: {str(e)}")
                                raise Exception(f"No se pudo transformar a UTM: {str(e)}")
                    
                    # Crear buffer en el CRS proyectado
                    centroid_point_geom = QgsGeometry.fromPointXY(centroid_for_buffer)
                    buffer_geom = centroid_point_geom.buffer(buffer_distance, 25)  # 25 segmentos para suavidad
                    
                    if buffer_geom.isEmpty() or not buffer_geom.isValid():
                        raise Exception("Buffer inválido o vacío")
                    
                    
                    # Transformar buffer al CRS de la capa de palmas si es necesario
                    if buffer_crs != palm_crs:
                        try:
                            transform = QgsCoordinateTransform(buffer_crs, palm_crs, QgsProject.instance())
                            buffer_geom.transform(transform)
                            logger.info(f"Buffer transformado de {buffer_crs.authid()} a {palm_crs.authid()}")
                        except Exception as e:
                            logger.warning(f"Error en transformación de buffer: {str(e)}")
                            raise Exception(f"No se pudo transformar buffer: {str(e)}")
                    
                    # Filtrar palmas dentro del buffer
                    features_in_buffer = []
                    palm_count = 0
                    for feature in palm_layer.getFeatures():
                        palm_count += 1
                        geom = feature.geometry()
                        if geom and not geom.isEmpty():
                            try:
                                if buffer_geom.intersects(geom):
                                    features_in_buffer.append(feature)
                            except Exception as e:
                                logger.warning(f"Error verificando intersección con feature {palm_count}: {str(e)}")
                                continue
                    
                    # Log solo si hay problemas
                    if len(features_in_buffer) < 2:
                        logger.warning(f"Solo {len(features_in_buffer)} palmas encontradas en buffer de 50m")
                    
                    # Si no hay palmas en el buffer, usar método alternativo
                    if len(features_in_buffer) < 2:
                        logger.warning(f"Solo {len(features_in_buffer)} palmas en buffer, usando método alternativo")
                        max_features = min(100, total_features)
                        features = list(palm_layer.getFeatures())[:max_features]
                        logger.info(f"Usando método alternativo: {len(features)} features")
                    # Si hay más de 100 palmas, seleccionar las 100 más cercanas al centroide
                    elif len(features_in_buffer) > 100:
                        # El centroide ya está en el CRS correcto (centroid_for_buffer o transformado)
                        # Pero necesitamos asegurarnos de que esté en el CRS de la capa de palmas
                        centroid_in_palm_crs = centroid_for_buffer
                        if buffer_crs != palm_crs:
                            try:
                                transform = QgsCoordinateTransform(buffer_crs, palm_crs, QgsProject.instance())
                                centroid_transformed = transform.transform(centroid_for_buffer.x(), centroid_for_buffer.y())
                                centroid_in_palm_crs = QgsPointXY(centroid_transformed.x(), centroid_transformed.y())
                                logger.info(f"Centroide transformado para cálculo de distancias: {centroid_in_palm_crs.x():.2f}, {centroid_in_palm_crs.y():.2f}")
                            except Exception as e:
                                logger.warning(f"Error transformando centroide para distancias: {str(e)}")
                                # Intentar transformar desde el CRS original del lote
                                if lot_crs and lot_crs != palm_crs:
                                    try:
                                        transform = QgsCoordinateTransform(lot_crs, palm_crs, QgsProject.instance())
                                        centroid_transformed = transform.transform(centroid_point.x(), centroid_point.y())
                                        centroid_in_palm_crs = QgsPointXY(centroid_transformed.x(), centroid_transformed.y())
                                    except Exception as e2:
                                        logger.warning(f"Error en transformación alternativa: {str(e2)}")
                                        centroid_in_palm_crs = centroid_for_buffer
                        
                        # Calcular distancias al centroide y ordenar
                        features_with_distance = []
                        for feature in features_in_buffer:
                            geom = feature.geometry()
                            if geom:
                                try:
                                    point = geom.asPoint()
                                    distance = centroid_in_palm_crs.distance(point)
                                    features_with_distance.append((distance, feature))
                                except Exception as e:
                                    logger.warning(f"Error calculando distancia al centroide: {str(e)}")
                                    continue
                        
                        # Ordenar por distancia y tomar las 100 más cercanas
                        if features_with_distance:
                            features_with_distance.sort(key=lambda x: x[0])
                            features = [f[1] for f in features_with_distance[:100]]
                            logger.info(f"Seleccionadas las 100 palmas más cercanas al centroide")
                        else:
                            # Fallback si no se pudieron calcular distancias
                            features = features_in_buffer[:100]
                            logger.warning("No se pudieron calcular distancias, usando primeras 100")
                    else:
                        features = features_in_buffer
                        logger.info(f"Usando todas las {len(features)} palmas dentro del buffer")
                        
                except Exception as e:
                    logger.error(f"Error procesando buffer: {str(e)}")
                    logger.warning("Usando método alternativo debido a error")
                    # Fallback: usar las primeras 100 palmas como antes
                    max_features = min(100, total_features)
                    features = list(palm_layer.getFeatures())[:max_features]
                    logger.info(f"Usando método alternativo: {len(features)} features")
            
            if len(features) < 2:
                logger.error("ERROR: Se necesitan al menos 2 features")
                return None
            
            # Obtener puntos
            points = []
            for i, feature in enumerate(features):
                try:
                    geom = feature.geometry()
                    if geom:
                        point = geom.asPoint()
                        points.append(point)
                    else:
                        logger.warning(f"Feature {i} sin geometría")
                except Exception as e:
                    logger.warning(f"Feature {i} error: {str(e)}")
            
            if len(points) < 2:
                logger.error("ERROR: No se obtuvieron suficientes puntos")
                return None
            
            logger.info(f"Total de puntos seleccionados para cálculo: {len(points)}")
            
            # PASO 1: Calcular todas las distancias entre palmas
            all_distances = []
            total_pairs = len(points) * (len(points) - 1) // 2
            logger.info(f"Calculando {total_pairs} distancias entre {len(points)} puntos")
            
            # Calcular distancias (con logging reducido para mejor rendimiento)
            calculated = 0
            for i in range(len(points)):
                for j in range(i + 1, len(points)):
                    try:
                        point1 = points[i]
                        point2 = points[j]
                        distance = point1.distance(point2)
                        all_distances.append(distance)
                        calculated += 1
                        
                    except Exception as e:
                        logger.warning(f"Error calculando distancia {i}-{j}: {str(e)}")
            
            logger.info(f"Total de distancias calculadas: {len(all_distances)}")
            
            if not all_distances:
                logger.error("ERROR: No se calcularon distancias")
                return None
            
            # PASO 2: Filtro de rango (8-10 metros) - Distancias realistas para palma aceitera
            valid_distances = []
            discarded_count = 0
            for distance in all_distances:
                if 8.0 <= distance <= 10.0:  # Rango ajustado para palma aceitera (8-10 metros)
                    valid_distances.append(distance)
                else:
                    discarded_count += 1
            
            # Log solo si hay problemas
            if len(valid_distances) == 0:
                logger.warning(f"No se encontraron distancias válidas (8-10 m). Descartadas: {discarded_count}")
            
            if not valid_distances:
                logger.warning("No hay distancias en el rango válido, usando todas las distancias")
                valid_distances = all_distances
            
            distances = valid_distances
            
            if not distances:
                logger.error("ERROR: No se calcularon distancias")
                return None
            
            # PASO 3: Eliminación de outliers (distancias extremas)
            sorted_distances = sorted(distances)
            n = len(sorted_distances)
            
            # Calcular Q1 (percentil 25) y Q3 (percentil 75)
            q1_index = int(n * 0.25)
            q3_index = int(n * 0.75)
            q1 = sorted_distances[q1_index]
            q3 = sorted_distances[q3_index]
            
            # Calcular IQR (Rango Intercuartílico)
            iqr = q3 - q1
            
            # Eliminar outliers (valores fuera de Q1 - 1.5*IQR y Q3 + 1.5*IQR)
            lower_bound = q1 - 1.5 * iqr
            upper_bound = q3 + 1.5 * iqr
            
            filtered_distances = []
            outliers_removed = 0
            for distance in sorted_distances:
                if lower_bound <= distance <= upper_bound:
                    filtered_distances.append(distance)
                else:
                    outliers_removed += 1
            
            if not filtered_distances:
                logger.warning("Todos los valores son outliers, usando distancias originales")
                filtered_distances = sorted_distances
            
            # Log solo si hay muchos outliers
            if outliers_removed > len(filtered_distances) * 0.3:
                logger.warning(f"Muchos outliers eliminados: {outliers_removed} de {len(sorted_distances)} distancias")
            
            # PASO 4: Estadísticas robustas usando percentil 25
            
            # Usar percentil 25 en lugar de mínimo (más robusto)
            p25_index = int(len(filtered_distances) * 0.25)
            p75_index = int(len(filtered_distances) * 0.75)
            
            p25_distance = filtered_distances[p25_index]  # Percentil 25 (más robusto que mínimo)
            p75_distance = filtered_distances[p75_index]  # Percentil 75
            
            # Calcular mediana
            n_filtered = len(filtered_distances)
            if n_filtered % 2 == 0:
                median_dist = (filtered_distances[n_filtered//2 - 1] + filtered_distances[n_filtered//2]) / 2
            else:
                median_dist = filtered_distances[n_filtered//2]
            
            # Promedio de las distancias filtradas
            avg_dist = sum(filtered_distances) / len(filtered_distances)
            
            # Log solo el resultado final
            logger.info(f"Distancia entre palmas calculada: {p25_distance:.2f} m (de {len(filtered_distances)} distancias analizadas)")
            
            return {
                'median_distance': median_dist,
                'avg_distance': avg_dist,
                'min_distance': p25_distance,  # Usar percentil 25 en lugar de mínimo
                'max_distance': p75_distance,   # Usar percentil 75 en lugar de máximo
                'most_common': round(median_dist),
                'total_palms': len(points),
                'total_distances': len(filtered_distances),
                'p25_distance': p25_distance,  # Nueva métrica robusta
                'outliers_removed': outliers_removed
            }
            
        except Exception as e:
            import traceback
            error_details = traceback.format_exc()
            logger.error(f"ERROR en cálculo de distancia: {str(e)}")
            logger.error(f"Traceback completo:\n{error_details}")
            return None

