    def calculate_line1_from_popup(self, dialog):
        """Muestra la geometría de siembra medida, ya con las 4 palmas elegidas.

        Acá no se crea ninguna capa. Antes se generaba una "vista previa" con los
        mismos nombres que el resultado final (LineasLote_X / PalmasNumeradas_X),
        que el botón de procesar después borraba y rehacía: parecía que el
        trabajo ya estaba hecho, y encima mostraba el azimut crudo de los dos
        clics, que no es el que se usa. La orientación buena se mide sobre las
        palmas detectadas (ver _measure_planting_geometry), así que lo único
        útil para mostrar en este paso es esa medición.
        """
        import math

        try:
            logger.info("=== MIDIENDO GEOMETRÍA DE LA SIEMBRA ===")

            missing = []
            if not getattr(self, 'first_palm_coords', None):
                missing.append("primera palma de línea 1")
            if not getattr(self, 'last_palm_coords', None):
                missing.append("última palma de línea 1")
            if not getattr(self, 'first_palm_l2_coords', None):
                missing.append("primera palma de línea 2")
            if not getattr(self, 'last_palm_l2_coords', None):
                missing.append("última palma de línea 2")
            if missing:
                QtWidgets.QMessageBox.warning(
                    dialog, "Advertencia",
                    "Por favor, seleccione: " + ", ".join(missing) + "."
                )
                return

            p1, p2 = self.first_palm_coords, self.last_palm_coords
            q1, q2 = self.first_palm_l2_coords, self.last_palm_l2_coords

            def _unit(a, b):
                vx, vy = b['x'] - a['x'], b['y'] - a['y']
                norm = math.hypot(vx, vy)
                return None if norm < 1e-6 else (vx / norm, vy / norm)

            hint = _unit(p1, p2) or _unit(q1, q2)
            if hint is None:
                QtWidgets.QMessageBox.warning(
                    dialog, "No se puede determinar la orientación",
                    "Tanto la línea 1 como la línea 2 quedaron con una sola palma.\n\n"
                    "Seleccione un par de líneas más adentro del lote, donde al menos "
                    "una tenga 2 o más palmas."
                )
                return

            real_points = self._collect_real_palms(self._numbering_crs())
            if len(real_points) < 3:
                QtWidgets.QMessageBox.warning(
                    dialog, "Sin palmas detectadas",
                    "No se encontraron suficientes palmas detectadas para medir la siembra."
                )
                return

            ux, uy, step, row_spacing = self._measure_planting_geometry(
                real_points, hint[0], hint[1]
            )
            azimuth = math.degrees(math.atan2(ux, uy)) % 360

            if hasattr(self, 'azimuthLineEdit') and self.azimuthLineEdit:
                self.azimuthLineEdit.setText(f"{azimuth:.2f}")
            self.saved_azimuth = f"{azimuth:.2f}"

            detalles = [f"Eje de siembra {azimuth:.2f}°"]
            if step:
                detalles.append(f"palmas cada {step:.2f} m")
            if row_spacing:
                detalles.append(f"filas cada {row_spacing:.2f} m")
            logger.info("Geometría medida: " + ", ".join(detalles))

            self.iface.messageBar().pushMessage(
                "Geometría medida",
                " · ".join(detalles) + ". Ahora presione \"5 - Procesar Numeración\".",
                level=Qgis.Info, duration=8
            )

        except Exception as e:
            logger.error(f"Error al medir la geometría de la siembra: {str(e)}")
            import traceback
            logger.error(traceback.format_exc())
            QtWidgets.QMessageBox.critical(
                dialog, "Error",
                f"Error al medir la geometría de la siembra:\n\n{str(e)}"
            )

    def process_numbering_from_popup(self, dialog):
        """Genera la grilla en tresbolillo cuando se hace clic en 'Procesar Numeración'"""
        import math
        from qgis.core import QgsProject, QgsVectorLayer
        
        # Crear y mostrar pantalla de carga
        # Usar la ventana principal de QGIS como padre para evitar problemas de minimización
        main_window = self.iface.mainWindow() if hasattr(self, 'iface') and self.iface else dialog
        progress = QProgressDialog("Procesando numeración de palmas...\nPor favor espere...", "Cancelar", 0, 0, main_window)
        progress.setWindowTitle("Procesando")
        progress.setWindowModality(Qt.ApplicationModal)  # Cambiar a ApplicationModal en lugar de WindowModal
        progress.setMinimumDuration(0)  # Mostrar inmediatamente
        progress.setRange(0, 0)  # Modo indeterminado (barra animada)
        progress.setWindowFlags(Qt.Dialog | Qt.WindowTitleHint | Qt.CustomizeWindowHint)  # Evitar minimización
        progress.show()
        QApplication.processEvents()  # Procesar eventos para mostrar el diálogo
        
        try:
            logger.info("=== PROCESANDO NUMERACIÓN - GENERANDO GRILLA EN TRESBOLILLO ===")
            
            # Obtener el FID del lote
            lot_id = getattr(self, 'lot_id', None)
            if not lot_id:
                if hasattr(self, 'lotNumberLineEdit') and self.lotNumberLineEdit:
                    lot_id = self.lotNumberLineEdit.text().strip()
                if not lot_id:
                    QtWidgets.QMessageBox.warning(
                        dialog,
                        "Error",
                        "No se pudo obtener el ID del lote."
                    )
                    return
            
            logger.info(f"FID del lote: {lot_id}")
            
            # La distancia entre palmas acá es solo un respaldo: la buena se mide
            # sobre las palmas detectadas dentro de generate_rows_from_real_palms.
            distance_data = self.calculate_palm_distance() or {}
            palm_distance = (distance_data.get('median_distance')
                             or distance_data.get('min_distance')
                             or 0)

            crs = self._numbering_crs()

            # Cerrar el pop-up
            dialog.accept()

            try:
                # La numeración se arma siguiendo las palmas realmente detectadas
                # (ver generate_rows_from_real_palms); el mensaje final se muestra ahí.
                self.generate_rows_from_real_palms(
                    lot_id,
                    crs,
                    palm_distance,
                    progress=progress
                )
                
                # Cerrar pantalla de carga después de completar el proceso
                progress.close()
                progress.deleteLater()  # Asegurar que se elimine completamente
                QApplication.processEvents()  # Procesar eventos para cerrar el diálogo
                
                # Limpiar el formulario para permitir numerar otro lote
                self.clear_numbering_form()
                
            except Exception as e:
                # Cerrar pantalla de carga en caso de error
                progress.close()
                progress.deleteLater()
                QApplication.processEvents()
                logger.error(f"Error al generar grilla: {str(e)}")
                import traceback
                logger.error(traceback.format_exc())
                QtWidgets.QMessageBox.critical(
                    self,
                    "Error",
                    f"Error al generar la grilla en tresbolillo:\n\n{str(e)}"
                )
            
        except Exception as e:
            # Cerrar pantalla de carga en caso de error
            if 'progress' in locals():
                progress.close()
                progress.deleteLater()
                QApplication.processEvents()
            logger.error(f"Error al procesar numeración desde pop-up: {str(e)}")
            import traceback
            logger.error(traceback.format_exc())
            QtWidgets.QMessageBox.critical(
                dialog,
                "Error",
                f"Error al procesar numeración: {str(e)}"
            )

