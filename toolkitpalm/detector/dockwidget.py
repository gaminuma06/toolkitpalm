    def disconnect_global_signals(self):
        """Se desengancha de las señales globales de QGIS.

        Estas señales viven en QGIS, no en este panel, así que sobreviven a que
        el panel se destruya (por ejemplo al recargar el plugin). Si no se
        desconectan, la instancia vieja sigue recibiendo avisos y revienta al
        tocar botones que Qt ya borró."""
        for getter, slot in (
            (lambda: self.iface.mapCanvas().selectionChanged, self.on_selection_changed),
            (lambda: self.iface.currentLayerChanged, self._on_active_layer_changed),
            (lambda: QgsProject.instance().layersAdded, self._on_project_layers_changed),
            (lambda: QgsProject.instance().layersRemoved, self._on_project_layers_changed),
        ):
            try:
                getter().disconnect(slot)
            except (TypeError, RuntimeError, AttributeError):
                pass

