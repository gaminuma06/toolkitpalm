class MergeDetectionsSection(QtWidgets.QFrame):
    """
    Sección plegable embebida en el panel del Detector (no una ventana aparte):
    deja elegir, con checkboxes, dos o más capas de puntos ya cargadas en el
    proyecto (resultados de detecciones anteriores) y las une en una sola capa
    nueva. Arranca oculta — solo agrega alto (y por lo tanto scroll) al panel
    cuando el usuario la abre con el botón "Unificar Detecciones".
    """

    def __init__(self, on_merge_requested, parent=None):
        super().__init__(parent)
        self._on_merge_requested = on_merge_requested
        self.checkboxes = []

        self.setFrameShape(QtWidgets.QFrame.StyledPanel)
        self.setStyleSheet("""
            MergeDetectionsSection {
                background-color: #f8fafc;
                border: 1px solid #cbd5e1;
                border-radius: 6px;
            }
        """)

        layout = QtWidgets.QVBoxLayout(self)

        info_label = QtWidgets.QLabel(
            "Seleccione dos o más capas de detecciones para unirlas en una capa nueva."
        )
        info_label.setWordWrap(True)
        info_label.setStyleSheet("font-size: 11px; color: #475569;")
        layout.addWidget(info_label)

        self.empty_label = QtWidgets.QLabel("No hay capas de puntos cargadas en el proyecto todavía.")
        self.empty_label.setStyleSheet("color: #9ca3af; font-style: italic; font-size: 11px;")
        self.empty_label.setVisible(False)
        layout.addWidget(self.empty_label)

        self.checklist_widget = QtWidgets.QWidget()
        self.checklist_layout = QtWidgets.QVBoxLayout(self.checklist_widget)
        self.checklist_layout.setContentsMargins(0, 0, 0, 0)
        layout.addWidget(self.checklist_widget)

        name_row = QtWidgets.QHBoxLayout()
        name_row.addWidget(QtWidgets.QLabel("Nombre de la capa resultante:"))
        self.output_name_edit = QtWidgets.QLineEdit("palmas_unificado")
        name_row.addWidget(self.output_name_edit)
        layout.addLayout(name_row)

        button_row = QtWidgets.QHBoxLayout()
        self.merge_button = QtWidgets.QPushButton("Unificar")
        self.merge_button.setStyleSheet("""
            QPushButton {
                background-color: #005587; color: white; border: none;
                padding: 6px 14px; border-radius: 4px; font-weight: bold; font-size: 11px;
            }
            QPushButton:hover { background-color: #002856; }
        """)
        button_row.addStretch(1)
        button_row.addWidget(self.merge_button)
        layout.addLayout(button_row)

        self.merge_button.clicked.connect(self._on_merge_clicked)

    def refresh_layers(self, point_layers):
        """Repuebla la lista de checkboxes con las capas de puntos actuales del proyecto."""
        for cb in self.checkboxes:
            cb.setParent(None)
            cb.deleteLater()
        self.checkboxes = []

        self.empty_label.setVisible(not point_layers)
        for layer in point_layers:
            cb = QtWidgets.QCheckBox(f"{layer.name()}  ({layer.featureCount()} puntos)")
            cb.setProperty("layer_id", layer.id())
            self.checklist_layout.addWidget(cb)
            self.checkboxes.append(cb)

    def _on_merge_clicked(self):
        selected = [cb.property("layer_id") for cb in self.checkboxes if cb.isChecked()]
        if len(selected) < 2:
            QtWidgets.QMessageBox.warning(
                self, "Selección insuficiente", "Seleccione al menos 2 capas para unificar."
            )
            return
        name = self.output_name_edit.text().strip()
        if not name:
            QtWidgets.QMessageBox.warning(self, "Falta el nombre", "Ponele un nombre a la capa resultante.")
            return
        if self._on_merge_requested:
            self._on_merge_requested(selected, name)


