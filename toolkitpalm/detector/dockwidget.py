    def _get_toolkitpalm_shell(self):
        """Encuentra el panel contenedor de ToolkitPalm (el que agrupa Detector/Segmentador/etc.).

        Después de recargar el plugin puede quedar más de una instancia dando
        vueltas: las ya destruidas se descartan y se prefiere la que está
        visible, que es la que el usuario realmente está usando."""
        try:
            from qgis.PyQt import sip
        except ImportError:
            import sip

        candidates = []
        for widget in QApplication.allWidgets():
            if type(widget).__name__ != 'ToolkitPalmDockWidget':
                continue
            if sip.isdeleted(widget):
                continue
            candidates.append(widget)

        for widget in candidates:
            if widget.isVisible():
                return widget
        return candidates[-1] if candidates else None

    def _hide_toolkitpalm_panel(self):
        """
        Oculta el panel completo de ToolkitPalm mientras el usuario tiene que
        interactuar con el mapa (seleccionar puntos, editar, etc.), para
        dejarle toda la pantalla libre. Usar junto con _show_toolkitpalm_panel
        al terminar esa interacción.
        """
        if getattr(self, '_shell_hidden_by_tool', None) is not None:
            return  # ya estaba oculto por otra herramienta, no pisar la referencia
        shell = self._get_toolkitpalm_shell()
        if shell is not None:
            try:
                shell.hide()
            except RuntimeError:
                return
            self._shell_hidden_by_tool = shell

    def _show_toolkitpalm_panel(self):
        """Vuelve a mostrar el panel de ToolkitPalm oculto por _hide_toolkitpalm_panel."""
        shell = getattr(self, '_shell_hidden_by_tool', None)
        # La referencia se limpia siempre, incluso si mostrar falla: si quedara
        # colgada, _hide_toolkitpalm_panel cortaría de entrada para siempre y el
        # panel nunca volvería a esconderse al usar una herramienta.
        self._shell_hidden_by_tool = None
        if shell is not None:
            try:
                shell.show()
            except RuntimeError:
                pass

