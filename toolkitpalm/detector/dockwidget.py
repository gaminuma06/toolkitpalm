    def on_palm_selected_for_popup(self):
        """
        Maneja la selección de palma cuando se está seleccionando desde el pop-up
        """
        try:
            logger.info("=== on_palm_selected_for_popup llamado ===")
            
            if not hasattr(self, '_selecting_palm_type'):
                logger.warning("_selecting_palm_type no está definido")
                return
            
            logger.info(f"Tipo de palma a seleccionar: {self._selecting_palm_type}")
            
            palm_layer = self.get_latest_palm_layer()
            if not palm_layer:
                logger.warning("No se encontró capa de palmas")
                return
            
            selected_features = palm_layer.selectedFeatures()
            if not selected_features:
                logger.warning("No hay features seleccionadas")
                return
            
            feature = selected_features[0]
            geometry = feature.geometry()
            point = geometry.asPoint()
            
            logger.info(f"Feature seleccionada - FID: {feature.id()}, X: {point.x():.6f}, Y: {point.y():.6f}")
            
            # Guardar las coordenadas según el tipo
            coords_dict = {
                'fid': feature.id(),
                'x': point.x(),
                'y': point.y(),
                'feature': feature
            }
            if self._selecting_palm_type == 'first_palm':
                self.first_palm_coords = coords_dict
                logger.info(f"✓ Primera palma (Línea 1) guardada - FID: {feature.id()}, X: {point.x():.6f}, Y: {point.y():.6f}")
                if hasattr(self, 'select_last_palm_button'):
                    self.select_last_palm_button.setEnabled(True)
            elif self._selecting_palm_type == 'last_palm':
                self.last_palm_coords = coords_dict
                logger.info(f"✓ Última palma (Línea 1) guardada - FID: {feature.id()}, X: {point.x():.6f}, Y: {point.y():.6f}")
                # Ahora que línea 1 está completa (aunque sea con 1 sola palma real),
                # se habilita empezar con línea 2 -- siempre hace falta, no solo
                # cuando línea 1 resultó con una sola palma.
                if hasattr(self, 'select_palm1_l2_button'):
                    self.select_palm1_l2_button.setEnabled(True)
            elif self._selecting_palm_type == 'first_palm_l2':
                self.first_palm_l2_coords = coords_dict
                logger.info(f"✓ Primera palma (Línea 2) guardada - FID: {feature.id()}, X: {point.x():.6f}, Y: {point.y():.6f}")
                if hasattr(self, 'select_last_palm_l2_button'):
                    self.select_last_palm_l2_button.setEnabled(True)
            elif self._selecting_palm_type == 'last_palm_l2':
                self.last_palm_l2_coords = coords_dict
                logger.info(f"✓ Última palma (Línea 2) guardada - FID: {feature.id()}, X: {point.x():.6f}, Y: {point.y():.6f}")
            else:
                logger.warning(f"Tipo de palma desconocido: {self._selecting_palm_type}")
            
            # Limpiar selección
            palm_layer.removeSelection()
            
            # Desconectar evento
            try:
                if hasattr(self, '_popup_selection_connected') and self._popup_selection_connected:
                    self.iface.mapCanvas().selectionChanged.disconnect(self.on_palm_selected_for_popup)
                    self._popup_selection_connected = False
                    logger.info("Evento de selección desconectado")
            except Exception as e:
                logger.warning(f"Error al desconectar evento: {str(e)}")
            
            # Reabrir el pop-up con los datos actualizados
            if hasattr(self, '_numbering_dialog') and self._numbering_dialog:
                logger.info("Reabriendo pop-up y actualizando campos")
                self._numbering_dialog.show()
                self._numbering_dialog.raise_()
                self._numbering_dialog.activateWindow()
                # Actualizar los campos en el pop-up
                self.update_popup_fields()

                # Recién cuando están las 4 palmas (línea 1 y línea 2 completas) se
                # puede calcular la orientación real -- una sola línea no alcanza.
                all_four_set = (
                    getattr(self, 'first_palm_coords', None) and
                    getattr(self, 'last_palm_coords', None) and
                    getattr(self, 'first_palm_l2_coords', None) and
                    getattr(self, 'last_palm_l2_coords', None)
                )
                if self._selecting_palm_type == 'last_palm_l2' and all_four_set:
                    logger.info("Línea 1 y línea 2 completas -- calculando orientación automáticamente")
                    QTimer.singleShot(300, lambda: self.calculate_line1_from_popup(self._numbering_dialog))
            else:
                logger.warning("_numbering_dialog no está disponible")
            
        except Exception as e:
            logger.error(f"Error al procesar selección de palma: {str(e)}")
            import traceback
            logger.error(traceback.format_exc())
            if hasattr(self, '_numbering_dialog') and self._numbering_dialog:
                self._numbering_dialog.show()
    
