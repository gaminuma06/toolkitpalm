    def _collect_real_palms(self, target_crs):
        """Palmas realmente detectadas, como lista de (x, y) en target_crs.

        Excluye el punto auxiliar 'lote_label' (el rótulo del lote que la
        detección agrega en el centroide), que no es una palma.
        """
        from qgis.core import QgsGeometry

        layer = self.get_latest_palm_layer()
        if layer is None:
            return []

        transform = None
        try:
            if layer.crs().isValid() and target_crs.isValid() and layer.crs() != target_crs:
                transform = QgsCoordinateTransform(layer.crs(), target_crs, QgsProject.instance())
                transform.setBallparkTransformsAreAppropriate(True)
        except Exception as e:
            logger.warning(f"No se pudo preparar la transformación de CRS de palmas: {str(e)}")

        has_tipo = layer.fields().indexOf("tipo") >= 0
        points = []
        for feat in layer.getFeatures():
            if has_tipo and feat["tipo"] == "lote_label":
                continue
            geom = feat.geometry()
            if not geom or geom.isEmpty():
                continue
            if transform is not None:
                geom = QgsGeometry(geom)
                geom.transform(transform)
            pt = geom.asPoint()
            points.append((pt.x(), pt.y()))
        return points

    def _measure_planting_geometry(self, real_points, hint_ux, hint_uy):
        """Mide la geometría real de la siembra a partir de las palmas detectadas.

        Dos clics sobre un tramo corto no alcanzan para fijar la orientación: un
        error de un metro en el clic (o en el centro que calculó la detección)
        tuerce la dirección varios grados, y sobre un lote largo eso desvía las
        filas decenas de metros. Acá la dirección se saca de las propias palmas:
        se arma un histograma de las direcciones hacia los vecinos cercanos, que
        en una siembra en tresbolillo marca tres ejes a 60° entre sí, y se elige
        el eje más cercano a la dirección que indicó el usuario.

        Devuelve (ux, uy, paso_entre_palmas, separacion_entre_filas).
        """
        import math
        from qgis.core import QgsSpatialIndex, QgsFeature, QgsGeometry, QgsPointXY

        index = QgsSpatialIndex()
        store = {}
        for i, (x, y) in enumerate(real_points):
            feat = QgsFeature(i)
            feat.setGeometry(QgsGeometry.fromPointXY(QgsPointXY(x, y)))
            index.addFeature(feat)
            store[i] = (x, y)

        # Vecinos cercanos de cada palma: distancias y direcciones.
        MAX_NEIGHBOR_DIST = 14.0
        direction_bins = [0.0] * 180
        neighbor_dists = []
        neighbor_vectors = []
        for i, (x, y) in enumerate(real_points):
            for j in index.nearestNeighbor(QgsPointXY(x, y), 7):
                if j == i:
                    continue
                vx, vy = store[j][0] - x, store[j][1] - y
                dist = math.hypot(vx, vy)
                if dist > MAX_NEIGHBOR_DIST or dist < 1e-6:
                    continue
                neighbor_dists.append(dist)
                neighbor_vectors.append((vx, vy))
                angle = math.degrees(math.atan2(vx, vy)) % 180
                # Se reparte en un pequeño entorno para suavizar el histograma.
                for k in (-2, -1, 0, 1, 2):
                    direction_bins[int(angle + k) % 180] += 1

        if not neighbor_dists:
            return hint_ux, hint_uy, None, None

        neighbor_dists.sort()
        step = neighbor_dists[len(neighbor_dists) // 2]

        # Eje de siembra más marcado dentro de ±MAX_SNAP_DEG de lo que indicó el
        # usuario: su selección decide cuál de los tres ejes es "la fila", los
        # datos deciden la orientación exacta.
        MAX_SNAP_DEG = 15.0
        hint_angle = math.degrees(math.atan2(hint_ux, hint_uy)) % 180
        best_angle, best_score = None, 0.0
        for angle in range(180):
            diff = abs(angle - hint_angle)
            diff = min(diff, 180 - diff)
            if diff > MAX_SNAP_DEG:
                continue
            if direction_bins[angle] > best_score:
                best_angle, best_score = angle, direction_bins[angle]

        if best_angle is None:
            ux, uy = hint_ux, hint_uy
        else:
            rad = math.radians(best_angle)
            ux, uy = math.sin(rad), math.cos(rad)
            if ux * hint_ux + uy * hint_uy < 0:
                ux, uy = -ux, -uy
            logger.info(f"Eje de siembra medido: {best_angle}° (la selección indicaba {hint_angle:.2f}°)")

        # Separación entre filas: componente perpendicular de los vecinos que no
        # están sobre la misma fila.
        perp_ux, perp_uy = -uy, ux
        offsets = [abs(vx * perp_ux + vy * perp_uy) for vx, vy in neighbor_vectors]
        offsets = [o for o in offsets if o > 1.5]
        row_spacing = sorted(offsets)[len(offsets) // 2] if offsets else None

        return ux, uy, step, row_spacing

    def generate_rows_from_real_palms(self, lot_id, crs, palm_distance, progress=None):
        """Numera ÚNICAMENTE las palmas detectadas: nunca inventa un punto.

        El usuario marca la palma inicial y final de la línea 1 y de la línea 2.
        Esa selección define tres cosas: cuál de los ejes de siembra es "la fila",
        hacia qué lado avanzan las filas, y en qué sentido se numera dentro de
        cada fila. La orientación exacta, el paso entre palmas y la separación
        entre filas se miden sobre las palmas detectadas, no sobre los clics.

        Cada palma detectada se proyecta al sistema de la siembra (a lo largo de
        la fila y perpendicular a ella) y se agrupa con las que comparten fila.
        No se agrega ningún punto donde falte una palma: si hay un hueco, la
        numeración simplemente sigue con la palma que realmente está ahí.
        """
        import math
        import bisect

        if self.exigir_carpeta_de_resultados() is None:
            return None

        p1 = getattr(self, 'first_palm_coords', None)
        p2 = getattr(self, 'last_palm_coords', None)
        q1 = getattr(self, 'first_palm_l2_coords', None)
        q2 = getattr(self, 'last_palm_l2_coords', None)
        if not (p1 and p2 and q1 and q2):
            QtWidgets.QMessageBox.warning(
                None, "Faltan palmas",
                "Hacen falta las 4 palmas (inicio y fin de línea 1, inicio y fin de línea 2)."
            )
            return None

        def _unit(ax, ay, bx, by):
            vx, vy = bx - ax, by - ay
            norm = math.hypot(vx, vy)
            if norm < 1e-6:
                return None
            return vx / norm, vy / norm

        hint = _unit(p1['x'], p1['y'], p2['x'], p2['y']) or _unit(q1['x'], q1['y'], q2['x'], q2['y'])
        if hint is None:
            QtWidgets.QMessageBox.warning(
                None, "No se puede determinar la orientación",
                "Tanto la línea 1 como la línea 2 quedaron con una sola palma.\n\n"
                "Seleccione un par de líneas más adentro del lote, donde al menos una tenga 2 o más palmas."
            )
            return None

        real_points = self._collect_real_palms(crs)
        if len(real_points) < 3:
            QtWidgets.QMessageBox.warning(
                None, "Sin palmas detectadas",
                "No se encontraron suficientes palmas detectadas para numerar."
            )
            return None

        ux, uy, measured_step, measured_row_spacing = self._measure_planting_geometry(
            real_points, hint[0], hint[1]
        )
        perp_ux, perp_uy = -uy, ux

        step = measured_step or palm_distance
        if not step or step < 0.5:
            QtWidgets.QMessageBox.warning(
                None, "Distancia inválida",
                f"No se pudo determinar una distancia razonable entre palmas "
                f"(medida: {measured_step}, estimada: {palm_distance})."
            )
            return None

        # El lado hacia donde avanzan las filas lo decide la línea 2: solo importa
        # el signo de su componente perpendicular, así que no hace falta que el
        # clic haya caído justo enfrente de la palma 1 de la línea 1.
        side_offset = (q1['x'] - p1['x']) * perp_ux + (q1['y'] - p1['y']) * perp_uy
        if abs(side_offset) < 0.5:
            QtWidgets.QMessageBox.warning(
                None, "Línea 2 sobre la misma fila",
                "La línea 2 quedó sobre la misma fila que la línea 1.\n\n"
                "Seleccione como línea 2 una fila vecina, no otra palma de la misma fila."
            )
            return None
        side = 1 if side_offset > 0 else -1

        row_spacing = measured_row_spacing or abs(side_offset)
        if row_spacing < 0.5:
            QtWidgets.QMessageBox.warning(
                None, "Separación entre filas inválida",
                f"No se pudo determinar la separación entre filas (medida: {measured_row_spacing})."
            )
            return None

        logger.info(
            f"Numeración: {len(real_points)} palmas detectadas, paso={step:.2f} m, "
            f"separación entre filas={row_spacing:.2f} m"
        )

        if progress is not None:
            QApplication.processEvents()
            if progress.wasCanceled():
                return None

        # Coordenadas de la siembra: 'pr' a lo largo de la fila, 'pe' perpendicular.
        # La base (u, perp) es ortonormal, así que cada palma se describe sin pérdida.
        projected = [((x * ux + y * uy), (x * perp_ux + y * perp_uy), x, y)
                     for x, y in real_points]

        base_pe = p1['x'] * perp_ux + p1['y'] * perp_uy

        def _median(values):
            ordered = sorted(values)
            return ordered[len(ordered) // 2]

        # Las filas se descubren por los huecos reales de la proyección
        # perpendicular, no por múltiplos de la separación medida. Con múltiplos,
        # una fila corta que cayera sobre el límite entre dos de ellos quedaba
        # repartida entre las filas vecinas y desaparecía; y una fila cuyas palmas
        # quedaran a ambos lados del límite se partía en dos.
        # Dentro de una fila las palmas se proyectan casi al mismo valor; al pasar
        # a la fila siguiente hay un salto cercano a la separación entre filas.
        ordenados = sorted(projected, key=lambda item: item[1])
        UMBRAL_FILA = row_spacing * 0.40
        grupos, actual = [], [ordenados[0]]
        for anterior, siguiente in zip(ordenados, ordenados[1:]):
            if siguiente[1] - anterior[1] > UMBRAL_FILA:
                grupos.append(actual)
                actual = [siguiente]
            else:
                actual.append(siguiente)
        grupos.append(actual)

        # Si una palma muy corrida "puentea" el hueco entre dos filas vecinas, el
        # agrupamiento anterior las encadena en una sola. Se reconoce porque el
        # grupo abarca, de lado a lado, bastante más de lo que ocupa una fila: en
        # ese caso se parte por su mayor hueco interno, hasta que cada parte entre
        # en el ancho de una fila.
        MAX_ANCHO_FILA = row_spacing * 0.75

        def _partir(grupo):
            if len(grupo) < 2 or grupo[-1][1] - grupo[0][1] <= MAX_ANCHO_FILA:
                return [grupo]
            corte = max(range(len(grupo) - 1),
                        key=lambda i: grupo[i + 1][1] - grupo[i][1])
            return _partir(grupo[:corte + 1]) + _partir(grupo[corte + 1:])

        separados = []
        for grupo in grupos:
            separados.extend(_partir(grupo))
        if len(separados) > len(grupos):
            logger.info(f"Se separaron {len(separados) - len(grupos)} filas que habían quedado encadenadas")

        centers = sorted(_median([it[1] for it in grupo]) for grupo in separados)

        # El centro de cada fila es la MEDIANA de sus palmas (no el promedio, para
        # que una palma corrida no lo arrastre). Reasignar al centro más cercano y
        # recalcular estabiliza el caso en que una palma muy desviada une dos filas
        # al agrupar por huecos.
        refined = {}
        for _ in range(3):
            refined = {}
            for item in projected:
                pos = bisect.bisect_left(centers, item[1])
                best_center, best_dist = None, None
                for idx in (pos - 1, pos, pos + 1):
                    if 0 <= idx < len(centers):
                        dist = abs(centers[idx] - item[1])
                        if best_dist is None or dist < best_dist:
                            best_center, best_dist = centers[idx], dist
                refined.setdefault(best_center, []).append(item)
            nuevos = sorted(_median([it[1] for it in items]) for items in refined.values())
            if nuevos == centers:
                break
            centers = nuevos

        # Las filas se ordenan desde la línea 1 hacia el lado que marcó la línea 2.
        forward, behind = [], []
        for center, items in refined.items():
            offset = (center - base_pe) * side
            (forward if offset >= -row_spacing * 0.5 else behind).append((offset, items))
        forward.sort(key=lambda pair: pair[0])

        rows = []
        for _offset, items in forward:
            # Dentro de la fila se numera en el sentido que marcó la línea 1.
            items.sort(key=lambda it: it[0])
            rows.append([(it[2], it[3]) for it in items])

        if not rows:
            QtWidgets.QMessageBox.warning(
                None, "Sin filas",
                "No se pudo agrupar ninguna fila con las palmas detectadas."
            )
            return None

        palmas_detras = sum(len(items) for _offset, items in behind)
        logger.info(
            f"Filas: {len(rows)}, palmas numeradas: {sum(len(r) for r in rows)}, "
            f"palmas antes de la línea 1 (sin numerar): {palmas_detras}"
        )

        return self._write_numbering_layers(
            rows, crs, lot_id, axis=(ux, uy), palmas_detras=palmas_detras
        )

    def _write_numbering_layers(self, rows, crs, lot_id, axis=None, palmas_detras=0):
        """Crea (reemplazando las anteriores) las capas de palmas numeradas y de
        líneas. Cada punto es una palma detectada: acá no se inventa ninguno."""
        from qgis.core import (QgsVectorLayer, QgsFeature, QgsGeometry, QgsPointXY,
                               QgsField, QgsProject)
        from qgis.PyQt.QtCore import QVariant

        points_name = f"PalmasNumeradas_{lot_id}"
        lines_name = f"LineasLote_{lot_id}"

        for name in (points_name, lines_name):
            for layer in list(QgsProject.instance().mapLayers().values()):
                if isinstance(layer, QgsVectorLayer) and layer.name() == name:
                    QgsProject.instance().removeMapLayer(layer.id())

        lote_display_name = str(lot_id)
        if hasattr(self, 'lotNameEdit') and self.lotNameEdit and self.lotNameEdit.text().strip():
            lote_display_name = self.lotNameEdit.text().strip()

        crs_authid = crs.authid() if crs and crs.isValid() else "EPSG:4326"

        points_layer = QgsVectorLayer(f"Point?crs={crs_authid}", points_name, "memory")
        points_layer.dataProvider().addAttributes([
            QgsField("ID", QVariant.Int),
            QgsField("Linea", QVariant.Int),
            QgsField("Palma", QVariant.Int),
            QgsField("X", QVariant.Double),
            QgsField("Y", QVariant.Double),
            QgsField("Lote", QVariant.String),
        ])
        points_layer.updateFields()

        lines_layer = QgsVectorLayer(f"LineString?crs={crs_authid}", lines_name, "memory")
        lines_layer.dataProvider().addAttributes([
            QgsField("ID", QVariant.Int),
            QgsField("Linea", QVariant.Int),
            QgsField("Palmas", QVariant.Int),
            QgsField("Lote", QVariant.String),
        ])
        lines_layer.updateFields()

        point_features = []
        line_features = []
        global_id = 1

        for line_index, row in enumerate(rows, start=1):
            for palm_index, (x, y) in enumerate(row, start=1):
                feature = QgsFeature(points_layer.fields())
                feature.setGeometry(QgsGeometry.fromPointXY(QgsPointXY(x, y)))
                feature.setAttribute("ID", global_id)
                feature.setAttribute("Linea", line_index)
                feature.setAttribute("Palma", palm_index)
                feature.setAttribute("X", x)
                feature.setAttribute("Y", y)
                feature.setAttribute("Lote", lote_display_name)
                point_features.append(feature)
                global_id += 1

            if len(row) >= 2:
                line_feature = QgsFeature(lines_layer.fields())
                line_feature.setGeometry(QgsGeometry.fromPolylineXY(
                    self._row_line_points(row, axis)
                ))
                line_feature.setAttribute("ID", line_index)
                line_feature.setAttribute("Linea", line_index)
                line_feature.setAttribute("Palmas", len(row))
                line_feature.setAttribute("Lote", lote_display_name)
                line_features.append(line_feature)

        points_layer.dataProvider().addFeatures(point_features)
        lines_layer.dataProvider().addFeatures(line_features)
        points_layer.updateExtents()
        lines_layer.updateExtents()

        # Guardar en disco antes de cargarlas: en memoria se pierden al cerrar
        # QGIS sin guardar el proyecto, y el trabajo de numerar un lote no es
        # algo que convenga perder por eso.
        puntos_guardado = self._guardar_capa_numeracion(points_layer, lote_display_name, "numeradas", crs)
        lineas_guardado = self._guardar_capa_numeracion(lines_layer, lote_display_name, "lineas", crs)
        if puntos_guardado is not None:
            points_layer = puntos_guardado
        if lineas_guardado is not None:
            lines_layer = lineas_guardado

        QgsProject.instance().addMapLayer(lines_layer)
        QgsProject.instance().addMapLayer(points_layer)

        self._style_numbering_layers(points_layer, lines_layer)

        mensaje = (f"Se numeraron {len(point_features)} palmas en {len(rows)} líneas.\n\n"
                   "Todos los puntos corresponden a palmas detectadas: no se agregó ninguno.")
        if puntos_guardado is not None:
            mensaje += f"\n\nGuardado en:\n{os.path.dirname(puntos_guardado.source())}"
        if palmas_detras:
            mensaje += (f"\n\nQuedaron {palmas_detras} palmas detectadas antes de la línea 1, "
                        "sin numerar. Si el lote empieza antes, seleccione como línea 1 una fila "
                        "más al borde y repita la numeración.")
        QtWidgets.QMessageBox.information(None, "Numeración completada", mensaje)
        return points_layer

    def _guardar_capa_numeracion(self, capa_memoria, lote, sufijo, crs):
        """Escribe la capa en la carpeta del lote y devuelve la capa ya en disco.

        Devuelve None si no hay carpeta de resultados configurada o si falla el
        guardado: en ese caso se sigue usando la capa en memoria, que al menos
        deja ver el resultado."""
        from qgis.core import QgsVectorFileWriter, QgsVectorLayer
        from .worker import carpeta_del_lote, nombre_seguro

        carpeta = carpeta_del_lote(self.carpeta_de_resultados(), lote)
        if carpeta is None:
            QtWidgets.QMessageBox.warning(
                self, "No se pudo guardar",
                "No se pudo crear la carpeta del lote dentro de la carpeta de "
                "resultados. Revise la ruta elegida."
            )
            return None

        base = f"{nombre_seguro(lote)}_{sufijo}"
        destino = os.path.join(carpeta, f"{base}.shp")
        # Numerar de nuevo el mismo lote reemplaza el resultado anterior: son la
        # misma información, no dos versiones que convenga conservar.
        try:
            error = QgsVectorFileWriter.writeAsVectorFormat(
                capa_memoria, destino, "utf-8", crs, "ESRI Shapefile"
            )
            if isinstance(error, tuple):
                error = error[0]
            if error != QgsVectorFileWriter.NoError:
                logger.warning(f"No se pudo guardar {destino}: código {error}")
                return None
        except Exception as e:
            logger.warning(f"No se pudo guardar {destino}: {e}")
            return None

        en_disco = QgsVectorLayer(destino, capa_memoria.name(), "ogr")
        if not en_disco.isValid():
            logger.warning(f"El archivo guardado no se pudo abrir: {destino}")
            return None
        logger.info(f"Capa de numeración guardada en {destino}")
        return en_disco

    def _row_line_points(self, row, axis):
        """Extremos de la línea de una fila, apoyados en el eje de siembra.

        La línea se apoya en la MEDIANA de la posición perpendicular de sus
        palmas, no en el promedio ni en los extremos: así una palma corrida de
        su fila no inclina ni desplaza la línea, y como todas las filas usan el
        mismo eje medido, quedan paralelas entre sí."""
        from qgis.core import QgsPointXY

        if not axis:
            return [QgsPointXY(row[0][0], row[0][1]), QgsPointXY(row[-1][0], row[-1][1])]

        ux, uy = axis
        perp_ux, perp_uy = -uy, ux

        offsets = sorted(x * perp_ux + y * perp_uy for x, y in row)
        center = offsets[len(offsets) // 2]

        projections = [x * ux + y * uy for x, y in row]
        start, end = min(projections), max(projections)

        return [
            QgsPointXY(start * ux + center * perp_ux, start * uy + center * perp_uy),
            QgsPointXY(end * ux + center * perp_ux, end * uy + center * perp_uy),
        ]

    def estilo_palmas_numeradas(self, points_layer):
        """Puntos azules con la etiqueta 'L<linea> P<palma>' sobre cada palma.

        Se usa tanto en la capa que sale de numerar un lote como en la capa
        unificada: si los puntos traen línea y palma, se rotulan igual, venga de
        donde venga la capa."""
        from qgis.core import (QgsSymbol, QgsSingleSymbolRenderer, QgsPalLayerSettings,
                               QgsTextFormat, QgsTextBufferSettings, QgsVectorLayerSimpleLabeling)
        from qgis.PyQt.QtGui import QColor, QFont

        try:
            symbol = QgsSymbol.defaultSymbol(points_layer.geometryType())
            symbol.setColor(QColor(0, 0, 255))
            symbol.setSize(3)
            points_layer.setRenderer(QgsSingleSymbolRenderer(symbol))
        except Exception as e:
            logger.warning(f"No se pudo aplicar simbología a los puntos: {str(e)}")

        try:
            settings = QgsPalLayerSettings()
            settings.fieldName = "concat('L', \"Linea\", ' P', \"Palma\")"
            settings.isExpression = True

            text_format = QgsTextFormat()
            text_format.setFont(QFont("Arial", 7))
            text_format.setSize(7)
            text_format.setColor(QColor(255, 255, 0))

            buffer_settings = QgsTextBufferSettings()
            buffer_settings.setEnabled(True)
            buffer_settings.setSize(0.8)
            buffer_settings.setColor(QColor(0, 0, 0))
            text_format.setBuffer(buffer_settings)

            settings.setFormat(text_format)
            settings.displayAll = True
            points_layer.setLabeling(QgsVectorLayerSimpleLabeling(settings))
            points_layer.setLabelsEnabled(True)
        except Exception as e:
            logger.warning(f"No se pudieron configurar las etiquetas: {str(e)}")

        points_layer.triggerRepaint()

    def capa_tiene_numeracion(self, layer):
        """True si la capa trae línea y palma, o sea si se puede rotular como numerada."""
        nombres = {c.name().lower() for c in layer.fields()}
        return "linea" in nombres and "palma" in nombres

    def _style_numbering_layers(self, points_layer, lines_layer):
        """Estilo de las dos capas que produce la numeración: puntos rotulados
        y líneas azules."""
        from qgis.core import QgsSymbol, QgsSingleSymbolRenderer
        from qgis.PyQt.QtGui import QColor

        self.estilo_palmas_numeradas(points_layer)

        try:
            symbol = QgsSymbol.defaultSymbol(lines_layer.geometryType())
            symbol.setColor(QColor(0, 0, 255))
            symbol.setWidth(0.6)
            lines_layer.setRenderer(QgsSingleSymbolRenderer(symbol))
        except Exception as e:
            logger.warning(f"No se pudo aplicar simbología a las líneas: {str(e)}")

        lines_layer.triggerRepaint()
        try:
            self.iface.mapCanvas().refreshAllLayers()
        except Exception:
            pass

    def closeEvent(self, event):
        logger.info("Cerrando el plugin")
        
        # FORZAR OCULTACIÓN DEL BOTÓN AL CERRAR EL PLUGIN
        if hasattr(self, 'activatePalmNumberingButton'):
            self.activatePalmNumberingButton.setVisible(False)
            self.activatePalmNumberingButton.setEnabled(False)
            self.activatePalmNumberingButton.hide()
            logger.info("Botón de numeración OCULTO al cerrar plugin")
        if hasattr(self, 'editPalmsButton'):
            self.editPalmsButton.setVisible(False)
            self.editPalmsButton.setEnabled(False)

        # Desconectar eventos para evitar problemas al cerrar
        try:
            if hasattr(self, 'iface') and self.iface and hasattr(self, 'iface.mapCanvas'):
                self.iface.mapCanvas().selectionChanged.disconnect(self.on_selection_changed)
                logger.info("Eventos desconectados correctamente")
        except Exception as e:
            logger.warning(f"Error al desconectar eventos: {str(e)}")
        
        # Limpiar widgets personalizados
        try:
            if hasattr(self, 'lineEdit') and self.lineEdit:
                # Desconectar el portapapeles
                if hasattr(self.lineEdit, 'clipboard'):
                    self.lineEdit.clipboard.dataChanged.disconnect(self.lineEdit.clipboard_data_changed)
                logger.info("lineEdit personalizado limpiado")
                
            if hasattr(self, 'lineEdit_2') and self.lineEdit_2:
                # Desconectar el portapapeles
                if hasattr(self.lineEdit_2, 'clipboard'):
                    self.lineEdit_2.clipboard.dataChanged.disconnect(self.lineEdit_2.clipboard_data_changed)
                logger.info("lineEdit_2 personalizado limpiado")
        except Exception as e:
            logger.warning(f"Error al limpiar widgets personalizados: {str(e)}")
        
        # Mantener el estado de términos aceptados para futuras sesiones
        if hasattr(self, 'terms_accepted') and self.terms_accepted:
            logger.info("Manteniendo estado de términos aceptados para futuras sesiones")
        
        # Emitir señal de cierre pero NO eliminar el widget
        self.closingPlugin.emit()
        
        # Ocultar el widget en lugar de cerrarlo completamente
        self.hide()
        event.ignore()  # Ignorar el evento para evitar que se elimine el widget
