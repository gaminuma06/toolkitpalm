    def _preparar_scroll_del_panel(self):
        """Hace que el panel pueda desplazarse cuando su contenido no cabe.

        Con widgetResizable, el área de scroll comprime el contenido hasta el
        tamaño de la ventana si el contenido se deja: entonces concluye que no
        hay nada que desplazar y no muestra la barra, aunque haya controles
        fuera de la vista. Con SetMinimumSize es Qt quien mantiene el alto
        mínimo del contenido según su layout, y lo rehace en cada cambio: el
        área ya no puede comprimirlo y la barra aparece cuando hace falta."""
        contenido = getattr(self, 'scrollAreaWidgetContents', None)
        if contenido is not None and contenido.layout() is not None:
            contenido.layout().setSizeConstraint(QtWidgets.QLayout.SetMinimumSize)

