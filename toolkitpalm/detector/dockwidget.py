    def handle_file_path(self, file_path, silent=False):
        """
        Maneja la ruta del archivo para ambos drag and drop y portapapeles.
        `silent=True` se usa cuando la llamada viene de reaccionar pasivamente
        al portapapeles (no de un arrastre o Ctrl+V deliberados en este campo):
        si la ruta no calza, no se muestra ningún error, simplemente se ignora.
        """
        print(f'Handling file path: {file_path}')

        if self.file_type == 'ortoimagen':
            if file_path.lower().endswith(('.tif', '.tiff', '.img', '.ecw', '.jp2', '.sid')):
                print('Aceptando archivo de imagen')
                self.setText(file_path)
                self.setStyleSheet("""
                    QLineEdit {
                        background-color: white;
                        border: 2px solid #00A9E0;
                        border-radius: 4px;
                        padding: 5px;
                    }
                """)
            elif not silent:
                print('Archivo de imagen no válido')
                QtWidgets.QMessageBox.warning(self, "Error",
                    "Por favor, arrastre una ortoimagen válida (.tif, .tiff, .img, .ecw, .jp2, .sid)")
                self.setStyleSheet("""
                    QLineEdit {
                        background-color: #FFEBEE;
                        border: 2px solid #F44336;
                        border-radius: 4px;
                        padding: 5px;
                    }
                """)
        elif self.file_type == 'lotes':
            if file_path.lower().endswith('.shp'):
                # Verificar que existan los archivos relacionados
                base_path = os.path.splitext(file_path)[0]
                required_files = ['.shp', '.dbf', '.shx', '.prj']
                missing_files = []

                for ext in required_files:
                    if not os.path.exists(base_path + ext):
                        missing_files.append(ext)

                if missing_files:
                    print(f'Faltan archivos del shapefile: {missing_files}')
                    if not silent:
                        QtWidgets.QMessageBox.warning(
                            self,
                            "Advertencia",
                            f"Faltan los siguientes archivos del shapefile: {', '.join(missing_files)}"
                        )
                    return

                print('Aceptando archivo shapefile')
                self.setText(file_path)
                self.setStyleSheet("""
                    QLineEdit {
                        background-color: white;
                        border: 2px solid #00A9E0;
                        border-radius: 4px;
                        padding: 5px;
                    }
                """)
            elif not silent:
                print('Archivo shapefile no válido')
                QtWidgets.QMessageBox.warning(self, "Error",
                    "Por favor, arrastre un shapefile válido (.shp)")
                self.setStyleSheet("""
                    QLineEdit {
                        background-color: #FFEBEE;
                        border: 2px solid #F44336;
                        border-radius: 4px;
                        padding: 5px;
                    }
                """)

    def clipboard_data_changed(self):
        """
        Reacciona a cambios del portapapeles DEL SISTEMA (Windows) — dispara con
        cualquier archivo copiado en cualquier programa, no solo con acciones
        dentro de QGIS. Por eso: solo actúa si este campo tiene el foco (indicio
        de que el usuario lo estaba usando a propósito) y nunca muestra errores
        si el contenido no calza — copiar cualquier archivo en Windows con QGIS
        abierto no debería interrumpir con un diálogo.
        """
        if not self.hasFocus():
            return
        mime_data = self.clipboard.mimeData()
        if mime_data.hasUrls():
            url = mime_data.urls()[0]
            file_path = url.toLocalFile()
            print(f'Clipboard changed - File path: {file_path}')
            self.handle_file_path(file_path, silent=True)

    def keyPressEvent(self, event):
        """Maneja eventos de teclado para copy/paste"""
        if event.matches(QKeySequence.Paste):
            mime_data = self.clipboard.mimeData()
            if mime_data.hasUrls():
                url = mime_data.urls()[0]
                file_path = url.toLocalFile()
                print(f'Paste event - File path: {file_path}')
                self.handle_file_path(file_path)
            else:
                super().keyPressEvent(event)
        else:
            super().keyPressEvent(event)

