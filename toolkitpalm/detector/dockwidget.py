    def authenticate_with_api(self, document, credential):
        """
        Autentica las credenciales (documento + contraseña) con la API. Sin distinción
        de rol: cualquier usuario registrado puede usar la herramienta.
        """
        try:
            import requests

            if not AUTH_ENABLED:
                logger.info("API de autenticación deshabilitada. Validando solo presencia de credenciales.")
                return {'success': True, 'message': 'Credenciales verificadas localmente'}

            auth_url = AUTH_ENDPOINT
            api_key = AUTH_API_KEY
            auth_data = {
                'documento': str(document).strip(),
                'clave': str(credential).strip()
            }

            logger.info("Autenticando usuario")

            # Headers que se van a enviar
            headers_to_send = {
                'Content-Type': 'application/json',
                'X-API-Key': api_key
            }
            
            # Realizar petición de autenticación
            response = requests.post(
                auth_url,
                json=auth_data,
                timeout=AUTH_TIMEOUT,
                headers=headers_to_send
            )
            
            # Log solo en caso de error
            if response.status_code != 200:
                logger.warning(f"Error API: {response.status_code}")
            
            if response.status_code == 200:
                try:
                    result = response.json()

                    # La API retorna "autenticado": 1 para autenticación exitosa
                    autenticado_value = result.get('autenticado')

                    if autenticado_value == 1:
                        logger.info("Autenticación exitosa")
                        mensaje_api = result.get('mensaje', 'Autenticación exitosa')
                        return {
                            'success': True,
                            'message': mensaje_api,
                            'user_info': result.get('user_info', result)
                        }
                    else:
                        logger.warning("Credenciales inválidas")
                        error_message = result.get('mensaje', 'Usuario no encontrado o credenciales incorrectas')
                        return {
                            'success': False,
                            'message': f"{error_message} (autenticado: {autenticado_value})"
                        }

                except ValueError as json_error:
                    logger.error(f"Error al parsear JSON de respuesta: {json_error}")
                    return {
                        'success': False, 
                        'message': f'Respuesta inválida del servidor de autenticación'
                    }
            else:
                # Manejar otros códigos de estado
                logger.error(f"Error en API de autenticación: {response.status_code} - {response.text}")
                
                # Intentar parsear la respuesta para obtener mensajes específicos
                try:
                    error_response = response.json()
                    
                    # Manejar el error de demasiados intentos
                    if "Demasiados intentos" in error_response.get('error', '') or \
                       "demasiados intentos" in error_response.get('message', '').lower():
                        logger.warning("Usuario ha excedido el límite de intentos de autenticación")
                        return {
                            'success': False,
                            'message': f"🚫 {error_response.get('message', 'Has excedido el límite de intentos. Intenta más tarde.')}"
                        }
                    
                    # Otros mensajes de error específicos
                    error_message = error_response.get('message', error_response.get('error', 'Error desconocido'))
                    return {
                        'success': False,
                        'message': f"Error: {error_message}"
                    }
                    
                except (ValueError, KeyError):
                    # Si no se puede parsear JSON, usar mensaje genérico
                    return {
                        'success': False, 
                        'message': f'Error del servidor de autenticación (código {response.status_code})'
                    }
                
        except requests.exceptions.Timeout:
            logger.error("Timeout en petición de autenticación")
            return {
                'success': False, 
                'message': 'Tiempo de espera agotado. Verifique su conexión a internet.'
            }
        except requests.exceptions.ConnectionError:
            logger.error("Error de conexión en petición de autenticación")
            return {
                'success': False, 
                'message': 'Error de conexión con el servidor de autenticación.'
            }
        except Exception as e:
            logger.error(f"Error durante autenticación con API: {str(e)}")
            return {
                'success': False, 
                'message': f'Error inesperado: {str(e)}'
            }

    def _browse_loaded_layers(self, button, layer_filter, empty_message):
        """
        Muestra un menú con las capas ya cargadas en el proyecto (filtradas por
        `layer_filter`) junto a `button`, más una opción para explorar el disco.
        Retorna la ruta del archivo fuente de la capa elegida, o None si el
        usuario eligió "Examinar archivo..." (caller debe abrir el QFileDialog)
        o canceló (retorna una tupla especial para distinguir ambos casos).

        Retorna: ("layer", file_path) | ("browse", None) | ("cancel", None)
        """
        from qgis.core import QgsProject

        candidatas = [lyr for lyr in QgsProject.instance().mapLayers().values() if layer_filter(lyr)]

        menu = QtWidgets.QMenu(self)
        if not candidatas:
            no_action = menu.addAction(empty_message)
            no_action.setEnabled(False)
            menu.addSeparator()
        else:
            for lyr in candidatas:
                action = menu.addAction(lyr.name())
                action.setData(lyr)
            menu.addSeparator()

        browse_action = menu.addAction("Examinar archivo en el disco...")

        chosen = menu.exec_(button.mapToGlobal(button.rect().bottomLeft()))
        if chosen is None:
            return ("cancel", None)
        if chosen is browse_action:
            return ("browse", None)

        layer = chosen.data()
        source_path = layer.source().split("|")[0]  # descarta parámetros extra de la URI (p.ej. capa dentro de un gpkg)
        return ("layer", source_path)

