    def on_authenticate_clicked(self):
        """
        Maneja el clic en el botón Autenticar
        """
        try:
            document = self.stored_credentials.get('document', '').strip()
            credential = self.stored_credentials.get('credential', '').strip()

            if not document or not credential:
                QtWidgets.QMessageBox.warning(
                    self, 
                    "Campos Incompletos", 
                    "Por favor complete los campos de documento y credencial."
                )
                return
            
            # Deshabilitar el botón mientras se autentica
            self.authenticateButton.setEnabled(False)
            self.authenticateButton.setText("Autenticando...")
            
            # Autenticar con la API
            logger.info("Iniciando autenticación desde botón...")
            auth_result = self.authenticate_with_api(document, credential)
            
            if auth_result['success']:
                # Autenticación exitosa
                self.is_authenticated = True
                self.auth_credentials['document'] = document
                self.auth_credentials['credential'] = credential
                
                # Actualizar interfaz para estado autenticado
                self.authenticateButton.setText("✓ Autenticado")
                self.authenticateButton.setEnabled(True)
                self.authenticateButton.setStyleSheet("""
                    QPushButton {
                        background-color: #002856;
                        color: white;
                        border: none;
                        border-radius: 4px;
                        padding: 8px;
                        font-weight: bold;
                    }
                """)
                
                # Habilitar campos de segmentación
                self.set_post_auth_fields_enabled(True)

                # Colapsar formulario y mostrar badge compacto
                self._show_auth_badge()

                # Guardar credenciales
                self.save_credentials()
                
                # Mostrar mensaje de éxito
                QtWidgets.QMessageBox.information(
                    self, 
                    "Autenticación Exitosa", 
                    f"¡Bienvenido! {auth_result['message']}"
                )
                logger.info("Autenticación exitosa desde botón")
            else:
                # Autenticación fallida
                self.is_authenticated = False
                self.authenticateButton.setText("Autenticar")
                self.authenticateButton.setEnabled(True)
                self.authenticateButton.setStyleSheet("")
                
                # Deshabilitar campos de segmentación
                self.set_post_auth_fields_enabled(False)
                
                # Mostrar mensaje de error
                QtWidgets.QMessageBox.warning(
                    self, 
                    "Autenticación Fallida", 
                    f"Error: {auth_result['message']}"
                )
                logger.warning(f"Autenticación fallida desde botón: {auth_result['message']}")
                print(f"Autenticación fallida desde botón: {auth_result['message']}")
            
            # Re-habilitar el botón
            self.authenticateButton.setEnabled(True)
            
        except Exception as e:
            error_msg = f"Error inesperado durante la autenticación: {str(e)}"
            logger.error(error_msg)
            QtWidgets.QMessageBox.critical(self, "Error", error_msg)
            self.authenticateButton.setText("Autenticar")
            self.authenticateButton.setEnabled(True)

