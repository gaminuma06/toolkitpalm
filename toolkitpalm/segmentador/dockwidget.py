    def _on_generate_range_layer(self, index_key):
        """Genera y carga una capa con solo los píxeles dentro del rango elegido en el slider."""
        data = self._index_stats_data.get(index_key)
        if not data:
            return

        page = self._index_stats_pages[index_key]
        low, high = page['slider'].low(), page['slider'].high()

        if low >= high:
            QtWidgets.QMessageBox.warning(
                self, "Rango inválido",
                "El rango debe tener un ancho mayor a cero. Ajusta los dos puntos del control deslizante."
            )
            return

        try:
            from .spectral_indices import generate_range_raster

            out_dir = os.path.dirname(data['tiff_path'])
            out_path = os.path.join(out_dir, f"rgb_indice_{index_key}_{low:.3f}_{high:.3f}.tif")
            generate_range_raster(data['tiff_path'], out_path, low, high)

            layer_name = f"Palmas — {index_key} ({low:.3f} a {high:.3f})"
            rlayer = QgsRasterLayer(out_path, layer_name, "gdal")
            if not rlayer.isValid():
                raise Exception(f"No se pudo cargar la capa por rango: {out_path}")

            self._apply_range_gradient_renderer(rlayer, low, high, data['percentiles'], data['color_stops'])
            QgsProject.instance().addMapLayer(rlayer)
            self.iface.setActiveLayer(rlayer)
            self.iface.zoomToActiveLayer()
            logger.info(f"Capa de rango [{low:.3f}, {high:.3f}] de {index_key} cargada: {out_path}")

        except Exception as e:
            QtWidgets.QMessageBox.critical(self, "Error al generar capa por rango", str(e))

    def _apply_range_gradient_renderer(self, rlayer, low, high, percentiles, color_stops):
        """Pinta la capa de rango con el degradado real de la rampa del índice
        entre low y high (mismo criterio de interpolación que la rampa completa
        aplicada en _apply_index_colormap, pero acotado al sub-rango elegido)."""
        try:
            from qgis.core import (QgsRasterShader, QgsColorRampShader,
                                   QgsSingleBandPseudoColorRenderer)
            from qgis.PyQt.QtGui import QColor
            from .spectral_indices import sample_ramp_color

            color_stops = color_stops or ["#8B0000", "#FF8C00", "#FFD700", "#7FFF00", "#006400"]

            anchors = sorted(set([low, high] + [p for p in percentiles if low < p < high]))
            items = []
            for anchor in anchors:
                r, g, b = sample_ramp_color(anchor, percentiles, color_stops)
                items.append(QgsColorRampShader.ColorRampItem(anchor, QColor(r, g, b), f"{anchor:.3f}"))

            shader = QgsRasterShader()
            color_ramp = QgsColorRampShader()
            color_ramp.setColorRampType(QgsColorRampShader.Interpolated)
            color_ramp.setColorRampItemList(items)
            shader.setRasterShaderFunction(color_ramp)

            renderer = QgsSingleBandPseudoColorRenderer(rlayer.dataProvider(), 1, shader)
            renderer.setClassificationMin(low)
            renderer.setClassificationMax(high)
            rlayer.setRenderer(renderer)
            rlayer.triggerRepaint()

        except Exception as e:
            logger.warning(f"No se pudo aplicar degradado de rango: {e}")

