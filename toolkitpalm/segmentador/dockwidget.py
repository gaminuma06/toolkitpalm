def _resolve_path_for_validation(path, iface=None):
    """
    Resuelve una ruta que puede venir de QGIS (ej. con prefijo ":/") o ser relativa,
    para que os.path.exists() y el resto del código encuentren el archivo.
    Retorna la ruta resuelta que existe, o None si no se puede resolver.
    """
    if not path or not path.strip():
        return None
    path = path.strip()
    # 1) Probar tal cual
    if os.path.exists(path):
        return path
    # 2) Prefijo ":/" que QGIS a veces usa (no es ruta de recurso Qt)
    if path.startswith(":/"):
        candidate = path[2:].lstrip("/").replace("/", os.sep)
        if os.path.exists(candidate):
            return candidate
        try:
            home = QgsProject.instance().homePath()
            if home:
                candidate = os.path.join(home, path[2:].lstrip("/").replace("/", os.sep))
                if os.path.exists(candidate):
                    return candidate
        except Exception:
            pass
    # 3) Normalizar y absoluta (relativas al directorio actual o al proyecto)
    try:
        normalized = os.path.normpath(path)
        if os.path.exists(normalized):
            return normalized
        abspath = os.path.abspath(path)
        if os.path.exists(abspath):
            return abspath
        if QgsProject.instance().homePath():
            with_project = os.path.join(QgsProject.instance().homePath(), path.replace("/", os.sep))
            if os.path.exists(with_project):
                return with_project
    except Exception:
        pass
    # 4) Si hay iface, buscar capa en el proyecto cuya source coincida (o sea la misma ruta resuelta)
    if iface:
        try:
            for layer in (iface.mapCanvas().layers() or []):
                src = (layer.source() or "").strip()
                if not src:
                    continue
                if os.path.normpath(src) == os.path.normpath(path):
                    return src
                if os.path.exists(src) and (src == path or os.path.normpath(src) == os.path.normpath(path)):
                    return src
                # Comparar por nombre de archivo por si la ruta está en otro formato
                if os.path.basename(src) == os.path.basename(path) and os.path.exists(src):
                    return src
        except Exception:
            pass
    return None


