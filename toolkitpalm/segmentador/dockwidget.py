    def _browse_loaded_layers(self, button, layer_filter, empty_message):
        """
        Muestra un menú con las capas ya cargadas en el proyecto (filtradas por
        `layer_filter`) junto a `button`, más una opción para explorar el disco.
        Mismo comportamiento que en el Detector, para que ambas herramientas
        se sientan iguales.

        Retorna: ("layer", file_path) | ("browse", None) | ("cancel", None)
        """
        candidatas = [lyr for lyr in QgsProject.instance().mapLayers().values() if layer_filter(lyr)]

        menu = QtWidgets.QMenu(self)
        if not candidatas:
            no_action = menu.addAction(empty_message)
            no_action.setEnabled(False)
            menu.addSeparator()
        else:
            for lyr in candidatas:
                action = menu.addAction(lyr.name())
                action.setData(lyr)
            menu.addSeparator()

        browse_action = menu.addAction("Examinar archivo en el disco...")

        chosen = menu.exec_(button.mapToGlobal(button.rect().bottomLeft()))
        if chosen is None:
            return ("cancel", None)
        if chosen is browse_action:
            return ("browse", None)

        layer = chosen.data()
        source_path = layer.source().split("|")[0]
        return ("layer", source_path)

