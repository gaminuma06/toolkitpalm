        available = get_available_indices(effective_bands)
        for key, display_name in available:
            self.combo.addItem(display_name, key)
        layout.addWidget(self.combo)

        self.desc_label = QLabel()
        self.desc_label.setWordWrap(True)
        self.desc_label.setStyleSheet("color: #007AAE; font-style: italic;")
        layout.addWidget(self.desc_label)

