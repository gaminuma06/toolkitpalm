    def validate_authentication(self):
        """
        Valida que los campos de autenticación estén completos y actualiza el estado de la interfaz
        """
        try:
            # Verificar si está autenticado
            if not self.is_authenticated:
                logger.info("Usuario no autenticado")
                return False
            
            # Verificar que las credenciales estén completas
            document = self.auth_credentials.get('document', '').strip()
            credential = self.auth_credentials.get('credential', '').strip()
            
            if not document or not credential:
                logger.warning("Credenciales incompletas")
                self.is_authenticated = False
                return False
            
            # Habilitar/deshabilitar el botón OK basado en la autenticación
            if hasattr(self, 'pushButton_3'):
                if self.is_authenticated:
                    # Solo habilitar si está autenticado Y hay archivos seleccionados Y lote seleccionado
                    has_image = hasattr(self, 'lineEdit') and self.lineEdit.text().strip()
                    has_lotes = hasattr(self, 'lineEdit_2') and self.lineEdit_2.text().strip()
                    has_lot = hasattr(self, 'lot_id') and self.lot_id is not None
                    self.pushButton_3.setEnabled(has_image and has_lotes and has_lot)
                else:
                    self.pushButton_3.setEnabled(False)
            
            logger.info("Autenticación validada correctamente")
            return True
            
        except Exception as e:
            logger.error(f"Error al validar autenticación: {str(e)}")
            return False

    def save_credentials(self):
        """
        Guarda las credenciales en la configuración de QGIS
        """
        try:
            from qgis.PyQt.QtCore import QSettings
            settings = QSettings()

            settings.setValue("segmentador_palmas/auth/document", self.auth_credentials.get('document', ''))
            
            # Guardar credencial de forma segura
            document = self.auth_credentials.get('document', '').strip()
            credential = self.auth_credentials.get('credential', '').strip()
            
            if document and credential:
                # Solo guardar si hay credenciales válidas
                settings.setValue("segmentador_palmas/auth/has_credential", True)
                # Guardar la credencial (en un entorno real, esto debería estar encriptado)
                settings.setValue("segmentador_palmas/auth/credential", credential)
            else:
                # Limpiar credenciales si están vacías
                settings.setValue("segmentador_palmas/auth/has_credential", False)
                settings.remove("segmentador_palmas/auth/credential")
            
            logger.info("Credenciales guardadas en configuración")
            
        except Exception as e:
            logger.error(f"Error al guardar credenciales: {str(e)}")

