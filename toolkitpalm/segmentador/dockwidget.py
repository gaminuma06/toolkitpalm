    def _apply_index_colormap(self, rlayer, index_key, output_path=None):
        """Aplica rampa de 5 colores basada en percentiles P5/P25/P50/P75/P95 del raster."""
        try:
            from .spectral_indices import SPECTRAL_INDICES
            from qgis.core import (QgsRasterShader, QgsColorRampShader,
                                   QgsSingleBandPseudoColorRenderer)
            from qgis.PyQt.QtGui import QColor
            import numpy as np
            from osgeo import gdal

            info = SPECTRAL_INDICES[index_key]
            color_stops = info.get("color_stops", ["#8B0000", "#FF8C00", "#FFD700", "#7FFF00", "#006400"])

            # Calcular percentiles reales de píxeles válidos (no NaN)
            percentiles = None
            if output_path and os.path.exists(output_path):
                try:
                    ds = gdal.Open(output_path)
                    if ds is not None:
                        arr = ds.GetRasterBand(1).ReadAsArray().astype(np.float32)
                        ds = None
                        nodata = rlayer.dataProvider().sourceNoDataValue(1)
                        if nodata is not None and not np.isnan(nodata):
                            arr[arr == np.float32(nodata)] = np.nan
                        valid = arr[~np.isnan(arr)]
                        if len(valid) >= 100:
                            percentiles = np.percentile(valid, [5, 25, 50, 75, 95]).tolist()
                            logger.info(f"Percentiles {index_key}: P5={percentiles[0]:.4f} P95={percentiles[4]:.4f}")

                            from .spectral_indices import compute_index_stats
                            stats = compute_index_stats(valid)
                            if stats:
                                self._update_index_stats_widget(index_key, stats, output_path)
                except Exception as pe:
                    logger.warning(f"No se pudieron calcular percentiles para {index_key}: {pe}")

            # Fallback: usar vmin/vmax del dict o estadísticas del layer
            if percentiles is None:
                vmin = info.get("vmin")
                vmax = info.get("vmax")
                if vmin is None or vmax is None:
                    stats = rlayer.dataProvider().bandStatistics(1)
                    vmin = stats.minimumValue
                    vmax = stats.maximumValue
                step = (vmax - vmin) / 4.0
                percentiles = [vmin, vmin + step, vmin + 2*step, vmin + 3*step, vmax]

            def hex_to_qcolor(hex_str):
                hex_str = hex_str.lstrip("#")
                r, g, b = int(hex_str[0:2], 16), int(hex_str[2:4], 16), int(hex_str[4:6], 16)
                return QColor(r, g, b)

            shader = QgsRasterShader()
            color_ramp = QgsColorRampShader()
            color_ramp.setColorRampType(QgsColorRampShader.Interpolated)
            items = [
                QgsColorRampShader.ColorRampItem(percentiles[i], hex_to_qcolor(color_stops[i]), f"{percentiles[i]:.3f}")
                for i in range(5)
            ]
            color_ramp.setColorRampItemList(items)
            shader.setRasterShaderFunction(color_ramp)

            renderer = QgsSingleBandPseudoColorRenderer(rlayer.dataProvider(), 1, shader)
            renderer.setClassificationMin(percentiles[0])
            renderer.setClassificationMax(percentiles[4])
            rlayer.setRenderer(renderer)
            rlayer.triggerRepaint()

        except Exception as e:
            logger.warning(f"No se pudo aplicar colormap para {index_key}: {e}")

