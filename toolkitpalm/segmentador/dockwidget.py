    def _update_index_stats_widget(self, index_key, stats, source_tiff_path):
        """Crea o actualiza la sección del acordeón correspondiente a index_key."""
        from .spectral_indices import SPECTRAL_INDICES

        info = SPECTRAL_INDICES[index_key]
        p5, p25, p50, p75, p95 = stats['percentiles']
        pct1, pct2, pct3, pct4, pct5 = stats['pct_bins']

        body_text = (
            f"Media: {stats['mean']:.3f}   Mediana: {stats['median']:.3f}   "
            f"Desv. est.: {stats['std']:.3f}\n"
            f"Mín: {stats['min']:.3f}   Máx: {stats['max']:.3f}\n"
            f"Percentiles P5/P25/P50/P75/P95: "
            f"{p5:.3f} / {p25:.3f} / {p50:.3f} / {p75:.3f} / {p95:.3f}\n"
            f"% píxeles por color: {pct1:.1f}% / {pct2:.1f}% / {pct3:.1f}% / {pct4:.1f}% / {pct5:.1f}%"
        )

        minimum, maximum = stats['min'], stats['max']
        percentiles = stats['percentiles']
        color_stops = info.get('color_stops')
        # Ventana visual del slider: P5-P95, no el mín/máx real. Índices con
        # denominadores que pueden acercarse a cero (ej. VARI) generan
        # outliers extremos que, si se usaran como ventana visual, dejan la
        # barra casi completamente pintada del color del extremo más cercano
        # y las manijas por defecto (P25/P75) montadas una sobre la otra.
        view_min, view_max = percentiles[0], percentiles[-1]
        default_low, default_high = percentiles[1], percentiles[3]  # P25 - P75
        step = max((maximum - minimum) / 200.0, 1e-6)

        if index_key in self._index_stats_pages:
            page = self._index_stats_pages[index_key]
            page['label'].setText(body_text)
            page['slider'].configure(minimum, maximum, percentiles, color_stops,
                                      low=default_low, high=default_high,
                                      view_min=view_min, view_max=view_max)
            for spin in (page['spin_low'], page['spin_high']):
                spin.blockSignals(True)
                spin.setRange(minimum, maximum)
                spin.setSingleStep(step)
                spin.blockSignals(False)
            page['spin_low'].setValue(default_low)
            page['spin_high'].setValue(default_high)
        else:
            container, lbl, slider, spin_low, spin_high = self._build_range_layer_section(index_key)
            lbl.setText(body_text)
            slider.configure(minimum, maximum, percentiles, color_stops,
                              low=default_low, high=default_high,
                              view_min=view_min, view_max=view_max)
            spin_low.setRange(minimum, maximum)
            spin_low.setSingleStep(step)
            spin_low.setValue(default_low)
            spin_high.setRange(minimum, maximum)
            spin_high.setSingleStep(step)
            spin_high.setValue(default_high)
            self._index_stats_pages[index_key] = {
                'widget': container, 'label': lbl, 'slider': slider,
                'spin_low': spin_low, 'spin_high': spin_high,
            }
            self.index_stats_widget.addItem(container, f"Estadísticas — {index_key}")

        self._index_stats_data[index_key] = {
            'tiff_path': source_tiff_path,
            'percentiles': stats['percentiles'],
            'color_stops': info.get('color_stops'),
            'stats': stats,
        }

        self.index_stats_widget.setCurrentWidget(self._index_stats_pages[index_key]['widget'])
        self.index_stats_widget.setVisible(True)

