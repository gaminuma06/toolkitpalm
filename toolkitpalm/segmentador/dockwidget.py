class SpectralIndexDialog(QDialog):
    """Diálogo para seleccionar y aplicar un índice espectral al TIFF segmentado."""

    def __init__(self, tiff_path, original_image_path=None, parent=None):
        super().__init__(parent)
        self.tiff_path = tiff_path
        self.original_image_path = original_image_path
        self.selected_index = None
        self.setWindowTitle("Aplicar índice espectral")
        self.setMinimumWidth(440)
        self._build_ui()

    def _build_ui(self):
        from .spectral_indices import detect_spectral_band_count, get_available_indices, SPECTRAL_INDICES
        from qgis.PyQt.QtWidgets import QComboBox

        layout = QVBoxLayout(self)

        title = QLabel("<b>Selecciona un índice espectral</b>")
        title.setStyleSheet("font-size: 13px; color: #002856;")
        layout.addWidget(title)

        # Contar solo bandas espectrales (excluye canal alfa)
        seg_bands = detect_spectral_band_count(self.tiff_path)
        orig_bands = detect_spectral_band_count(self.original_image_path) if self.original_image_path else 0

        # Usar la fuente con más bandas para determinar índices disponibles
        effective_bands = max(seg_bands, orig_bands)

        if seg_bands >= 3:
            src_label = f"Bandas espectrales del TIFF segmentado: <b>{seg_bands}</b>"
        elif orig_bands >= 3:
            src_label = (f"TIFF segmentado: {seg_bands} banda(s) espectral(es) — usando imagen original "
                         f"(<b>{orig_bands} bandas</b>) enmascarada por la segmentación")
        else:
            src_label = f"Bandas espectrales detectadas: segmentado={seg_bands}, original={orig_bands}"

        band_label = QLabel(src_label)
        band_label.setWordWrap(True)
        band_label.setStyleSheet("color: #555;")
        layout.addWidget(band_label)

        if effective_bands < 3:
            msg = QLabel(
                "No se detectaron suficientes bandas para calcular índices.<br>"
                f"<small>TIFF segmentado: {self.tiff_path}</small>"
            )
            msg.setWordWrap(True)
            layout.addWidget(msg)
            btn = QPushButton("Cerrar")
            btn.clicked.connect(self.reject)
            layout.addWidget(btn)
            return

