        if hasattr(self, 'terms_accepted') and self.terms_accepted:
            logger.info("Manteniendo estado de términos aceptados para futuras sesiones")
        
        # Emitir señal de cierre pero NO eliminar el widget
        self.closingPlugin.emit()
        
        # Ocultar el widget en lugar de cerrarlo completamente
        self.hide()
        event.ignore()  # Ignorar el evento para evitar que se elimine el widget

