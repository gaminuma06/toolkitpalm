        # tardar varios segundos, y sin esto la interfaz se queda "congelada"
        # en apariencia (sin ningún aviso) mientras procesa en el hilo principal.
        from qgis.PyQt.QtWidgets import QProgressDialog
        progress = QProgressDialog("Calculando índice espectral...", None, 0, 0, self)
        progress.setWindowTitle("Procesando")
        progress.setWindowModality(Qt.WindowModal)
        progress.setMinimumDuration(0)
        progress.setCancelButton(None)
        progress.show()
        QApplication.processEvents()

        try:
            from .spectral_indices import apply_spectral_index, detect_spectral_band_count
            from .worker import _apply_mask_to_multiband

            # Determinar el TIFF fuente para calcular el índice
            source_tiff = self.last_segmented_tiff
            seg_bands = detect_spectral_band_count(self.last_segmented_tiff)

            if seg_bands < 3 and self.last_original_image_path and os.path.exists(self.last_original_image_path):
                # El TIFF segmentado no tiene RGB: aplicar máscara sobre la imagen original
                out_dir = os.path.dirname(self.last_segmented_tiff)
                masked_path = os.path.join(out_dir, "ResultadoRGB_masked_source.tif")
                if not os.path.exists(masked_path):
                    result = _apply_mask_to_multiband(
                        self.last_segmented_tiff,
                        self.last_original_image_path,
                        masked_path
                    )
                    if not result:
                        raise Exception(
                            "No se pudo generar la capa de índice: el TIFF segmentado tiene "
                            f"{seg_bands} banda(s) y no se pudo enmascarar la imagen original."
                        )
                source_tiff = masked_path

            # Guardar en la carpeta de resultados con nombre corto y legible
            out_dir = os.path.dirname(self.last_segmented_tiff)
            out_path = os.path.join(out_dir, f"rgb_indice_{index_key}.tif")

            apply_spectral_index(source_tiff, index_key, out_path)

            layer_name = f"Palmas — {index_key}"
            rlayer = QgsRasterLayer(out_path, layer_name, "gdal")
            if not rlayer.isValid():
                raise Exception(f"No se pudo cargar la capa de índice: {out_path}")

            self._apply_index_colormap(rlayer, index_key, out_path)
            QgsProject.instance().addMapLayer(rlayer)
            self.iface.setActiveLayer(rlayer)
            self.iface.zoomToActiveLayer()
            logger.info(f"Índice {index_key} cargado: {out_path}")

        except Exception as e:
            QtWidgets.QMessageBox.critical(self, "Error al calcular índice", str(e))
        finally:
            progress.close()

