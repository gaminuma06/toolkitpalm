    def on_selection_changed(self):
        """
        Maneja el evento de cambio de selección en el canvas de QGIS
        """
        try:
            # Obtener la capa de lotes cargada
            lotes_path = self.lineEdit_2.text()
            if not lotes_path:
                return

            lotes_layer = None
            for layer in self.iface.mapCanvas().layers():
                if isinstance(layer, QgsVectorLayer) and layer.source().lower() == lotes_path.lower():
                    lotes_layer = layer
                    break

            if lotes_layer is None:
                logger.warning("No se encontró la capa de lotes en el canvas")
                return

            selected_features = lotes_layer.selectedFeatures()
            if selected_features:
                feature = selected_features[0]
                
                # Buscar el campo que contiene el nombre/código del lote
                lot_name_field = None
                for field_name in ['nombre', 'codigo', 'lote', 'name', 'code', 'lot', 'NOMBRE', 'CODIGO', 'LOTE', 'NAME', 'CODE', 'LOT']:
                    if lotes_layer.fields().indexFromName(field_name) >= 0:
                        lot_name_field = field_name
                        break
                
                # Si no encuentra campos específicos, usar el primer campo de texto
                if lot_name_field is None:
                    for field in lotes_layer.fields():
                        if field.type() in [10, 11, 12]:  # String, StringList, Date
                            lot_name_field = field.name()
                            break
                
                # Usar FID directamente usando la función helper (igual que el Detector)
                from .worker import get_lot_id_from_feature
                self.lot_id = get_lot_id_from_feature(feature)
                logger.info(f"Lote seleccionado - FID: {self.lot_id}, Capa: {lotes_layer.name()}")

                # Actualizar el estado de la interfaz
                self.buttonBox.button(QtWidgets.QDialogButtonBox.Ok).setEnabled(True)

                # Validar autenticación después de seleccionar lote
                self.validate_authentication()
            else:
                logger.info("No hay lotes seleccionados")
                self.lot_id = None
                self.buttonBox.button(QtWidgets.QDialogButtonBox.Ok).setEnabled(False)

        except Exception as e:
            logger.error(f"Error al manejar cambio de selección: {str(e)}")

    def run_segmentation(self):
        try:
            from .worker import run_segmentation as _run_segmentation_worker
            image_path_raw = self.lineEdit.text().strip()
            lotes_path_raw = self.lineEdit_2.text().strip()

            # Resolver rutas (QGIS a veces guarda ":/ruta" o rutas relativas que os.path.exists no reconoce)
            image_path = _resolve_path_for_validation(image_path_raw, getattr(self, 'iface', None))
            if image_path is None and image_path_raw and os.path.exists(image_path_raw):
                image_path = image_path_raw
            lotes_path = _resolve_path_for_validation(lotes_path_raw, getattr(self, 'iface', None))
            if lotes_path is None and lotes_path_raw and os.path.exists(lotes_path_raw):
                lotes_path = lotes_path_raw

            # Validar que las rutas existan
            if not image_path_raw:
                logger.error("Ruta de ortoimagen vacía")
                if hasattr(self, 'lineEdit') and self.lineEdit:
                    self.lineEdit.setStyleSheet("QLineEdit { background-color: #FFEBEE; border: 2px solid #F44336; border-radius: 4px; padding: 5px; }")
                QtWidgets.QMessageBox.critical(
                    self, "Error", "Indique la ruta de la ortoimagen."
                )
                return
            if not image_path or not os.path.exists(image_path):
                logger.error(f"Ruta de imagen no encontrada: {image_path_raw}")
                if hasattr(self, 'lineEdit') and self.lineEdit:
                    self.lineEdit.setStyleSheet("QLineEdit { background-color: #FFEBEE; border: 2px solid #F44336; border-radius: 4px; padding: 5px; }")
                QtWidgets.QMessageBox.critical(
                    self, "Error",
                    "La ruta de la ortoimagen no es válida o el archivo no existe.\n\n"
                    "Si arrastró una capa desde el panel, pruebe seleccionar el archivo con el botón «Subir»."
                )
                return
            # Actualizar campo con ruta resuelta para que la próxima vez no falle
            if image_path != image_path_raw and hasattr(self, 'lineEdit') and self.lineEdit:
                self.lineEdit.setText(image_path)
                self.lineEdit.setStyleSheet("QLineEdit { background-color: white; border: 2px solid #007AAE; border-radius: 4px; padding: 5px; }")

            if not lotes_path_raw:
                logger.error("Ruta de lotes vacía")
                if hasattr(self, 'lineEdit_2') and self.lineEdit_2:
                    self.lineEdit_2.setStyleSheet("QLineEdit { background-color: #FFEBEE; border: 2px solid #F44336; border-radius: 4px; padding: 5px; }")
                QtWidgets.QMessageBox.critical(
                    self, "Error", "Indique la ruta del shapefile de lotes."
                )
                return
            if not lotes_path or not os.path.exists(lotes_path):
                logger.error(f"Ruta de shapefile no encontrada: {lotes_path_raw}")
                if hasattr(self, 'lineEdit_2') and self.lineEdit_2:
                    self.lineEdit_2.setStyleSheet("QLineEdit { background-color: #FFEBEE; border: 2px solid #F44336; border-radius: 4px; padding: 5px; }")
                QtWidgets.QMessageBox.critical(
                    self, "Error",
                    "La ruta del shapefile no es válida o el archivo no existe.\n\n"
                    "Si arrastró una capa desde el panel, pruebe seleccionar el archivo con el botón «Subir»."
                )
                return
            if lotes_path != lotes_path_raw and hasattr(self, 'lineEdit_2') and self.lineEdit_2:
                self.lineEdit_2.setText(lotes_path)
                self.lineEdit_2.setStyleSheet("QLineEdit { background-color: white; border: 2px solid #007AAE; border-radius: 4px; padding: 5px; }")

            # Obtener la capa de lotes cargada en QGIS (comparar con ruta resuelta o original)
            lotes_layer = None
            for layer in self.iface.mapCanvas().layers():
                if not isinstance(layer, QgsVectorLayer):
                    continue
                src = (layer.source() or "").strip()
                if not src:
                    continue
                if src.lower() == lotes_path.lower() or src.lower() == lotes_path_raw.lower():
                    lotes_layer = layer
                    break
                try:
                    if os.path.normpath(src) == os.path.normpath(lotes_path) or os.path.normpath(src) == os.path.normpath(lotes_path_raw):
                        lotes_layer = layer
                        break
                except Exception:
                    pass

            if lotes_layer is None:
                logger.error("La capa de lotes no está cargada en el panel de capas")
                QtWidgets.QMessageBox.critical(
                    self,
                    "Error",
                    "La capa de lotes no está cargada en el panel de capas"
                )
                return

            selected_features = lotes_layer.selectedFeatures()
            if not selected_features:
                logger.error("No hay lotes seleccionados")
                QtWidgets.QMessageBox.critical(
                    self,
                    "Error",
                    "Debes seleccionar un lote para la detección.\nUsa la herramienta de selección de QGIS para seleccionar un lote."
                )
                return

            if len(selected_features) > 1:
                logger.error("Hay más de un lote seleccionado")
                QtWidgets.QMessageBox.critical(
                    self,
                    "Error",
                    "Debes seleccionar solo un lote para la detección."
                )
                return

            lote_feature = selected_features[0]
            
            # Buscar el campo que contiene el nombre/código del lote
            lot_name_field = None
            for field_name in ['nombre', 'codigo', 'lote', 'name', 'code', 'lot', 'NOMBRE', 'CODIGO', 'LOTE', 'NAME', 'CODE', 'LOT']:
                if lotes_layer.fields().indexFromName(field_name) >= 0:
                    lot_name_field = field_name
                    break
            
            # Si no encuentra campos específicos, usar el primer campo de texto
            if lot_name_field is None:
                for field in lotes_layer.fields():
                    if field.type() in [10, 11, 12]:  # String, StringList, Date
                        lot_name_field = field.name()
                        break
            
            # Usar FID directamente usando la función helper (igual que el Detector)
            from .worker import get_lot_id_from_feature
            self.lot_id = get_lot_id_from_feature(lote_feature)
            logger.info(f"FID del lote seleccionado: {self.lot_id}")
            
            # Verificar traslape entre el lote y la imagen
            try:
                # Cargar la imagen como capa raster
                raster_layer = QgsRasterLayer(image_path, "Imagen temporal")
                if not raster_layer.isValid():
                    raise Exception("No se pudo cargar la imagen como capa raster")
                
                # Verificar que la imagen tenga un SRC válido
                if not raster_layer.crs().isValid():
                    raise Exception("La imagen no tiene un sistema de coordenadas válido")
                
                # Obtener el SRC de la imagen
                raster_crs = raster_layer.crs()
                logger.info(f"SRC de la imagen: {raster_crs.description()}")
                
                # Obtener el SRC del lote
                lote_crs = lotes_layer.crs()
                logger.info(f"SRC del lote: {lote_crs.description()}")
                
                # Verificar si los SRC son diferentes
                if raster_crs != lote_crs:
                    logger.info("Los SRC son diferentes, realizando transformación")
                    # Crear una transformación de coordenadas
                    transform = QgsCoordinateTransform(lote_crs, raster_crs, QgsProject.instance())
                    
                    # Obtener la geometría del lote
                    lote_geometry = lote_feature.geometry()
                    
                    # Transformar la geometría al SRC de la imagen
                    lote_geometry.transform(transform)
                else:
                    # Si los SRC son iguales, usar la geometría directamente
                    lote_geometry = lote_feature.geometry()
                
                # Obtener la extensión de la imagen
                raster_extent = raster_layer.extent()
                logger.info(f"Extensión de la imagen: {raster_extent.toString()}")
                logger.info(f"Extensión del lote: {lote_geometry.boundingBox().toString()}")
                
                # Verificar si hay traslape
                if not lote_geometry.intersects(raster_extent):
                    logger.error("El lote seleccionado no se traslapa con la imagen")
                    QtWidgets.QMessageBox.critical(
                        self,
                        "Error de Traslape",
                        "El lote seleccionado no se traslapa con el área de la ortoimagen.\n\n"
                        "Por favor, seleccione un lote que se traslape con el área de la ortoimagen."
                    )
                    return
                
                # Calcular el área de traslape
                intersection = lote_geometry.intersection(QgsGeometry.fromRect(raster_extent))
                if intersection.isEmpty():
                    logger.error("El lote seleccionado no tiene área de traslape con la imagen")
                    QtWidgets.QMessageBox.critical(
                        self,
                        "Error de Traslape",
                        "El lote seleccionado no tiene área de traslape con la imagen.\n\n"
                        "Por favor, seleccione un lote que esté dentro o que se traslape con el área de la imagen."
                    )
                    return
                
                # Calcular el porcentaje de traslape
                lote_area = lote_geometry.area()
                intersection_area = intersection.area()
                overlap_percentage = (intersection_area / lote_area) * 100
                
                logger.info(f"Área del lote: {lote_area:.2f} unidades cuadradas")
                logger.info(f"Área de traslape: {intersection_area:.2f} unidades cuadradas")
                logger.info(f"Porcentaje de traslape: {overlap_percentage:.2f}%")
                
                # Validar el área del lote en hectáreas
                area_hectares = self.calculate_lot_area_hectares(lote_geometry, lotes_layer.crs())
                
                # Validar que el área esté dentro del rango permitido (1-50 hectáreas)
                if area_hectares is not None:
                    if area_hectares < 1.0:
                        logger.error(f"El área del lote ({area_hectares:.2f} hectáreas) es menor al mínimo permitido (1 hectárea)")
                        QtWidgets.QMessageBox.critical(
                            self,
                            "Área Insuficiente",
                            f"El área del lote seleccionado ({area_hectares:.2f} hectáreas) es menor al mínimo permitido (1 hectárea).\n\n"
                            "Por favor, seleccione un lote con un área mayor o igual a 1 hectárea."
                        )
                        return
                    elif area_hectares > 50.0:
                        logger.error(f"El área del lote ({area_hectares:.2f} hectáreas) excede el máximo permitido (50 hectáreas)")
                        QtWidgets.QMessageBox.critical(
                            self,
                            "Área Máxima Excedida",
                            f"El área del lote seleccionado ({area_hectares:.2f} hectáreas) excede el máximo permitido (50 hectáreas).\n\n"
                            "Por favor, seleccione un lote con un área menor o igual a 50 hectáreas."
                        )
                        return
                    else:
                        logger.info(f"Área del lote válida: {area_hectares:.2f} hectáreas (dentro del rango 1-50 hectáreas)")
                else:
                    logger.warning("No se pudo calcular el área en hectáreas, continuando sin validación de área")
                
                # Mostrar un mensaje más detallado sobre el traslape
                if overlap_percentage < 30.0:  # Si el traslape es menor al 30%
                    logger.error(f"El traslape es muy pequeño ({overlap_percentage:.2f}%)")
                    QtWidgets.QMessageBox.critical(
                        self,
                        "Traslape Insuficiente",
                        f"El traslape entre el lote y la imagen es muy pequeño ({overlap_percentage:.2f}%).\n\n"
                        "Para realizar una detección efectiva, el lote debe tener un traslape significativo con la imagen.\n\n"
                        "Por favor, seleccione un lote que tenga un mayor traslape con el área de la imagen."
                    )
                    return
                elif overlap_percentage < 50.0:  # Si el traslape es menor al 50%
                    logger.warning(f"El traslape es pequeño ({overlap_percentage:.2f}%)")
                    if QtWidgets.QMessageBox.No == QtWidgets.QMessageBox.question(
                        self,
                        "Traslape Reducido",
                        f"El traslape entre el lote y la imagen es pequeño ({overlap_percentage:.2f}%).\n\n"
                        "Esto podría afectar la calidad de la detección.\n\n"
                        "¿Desea continuar con la detección?",
                        QtWidgets.QMessageBox.Yes | QtWidgets.QMessageBox.No,
                        QtWidgets.QMessageBox.No
                    ):
                        return
                
                logger.info(f"Iniciando detección para lote ID: {self.lot_id}")
                
                # Preparar información del lote para el diálogo de confirmación
                lot_info = {'area_hectares': area_hectares} if area_hectares is not None else None
                
                # Mostrar diálogo de confirmación
                confirm_dialog = ConfirmDialog(self, lot_info)
                if confirm_dialog.exec_() == QtWidgets.QDialog.Accepted:
                    logger.info("Usuario confirmó la detección")
                    
                    try:
                        # Iniciar la segmentación
                        _run_segmentation_worker(self)
                        
                        # Mantener ortoimagen y lotes diligenciados para la siguiente segmentación
                        logger.info("Detección completada; ortoimagen y lotes se mantienen")
                        
                    except Exception as e:
                        error_msg = str(e)
                        if "index -1 is out of bounds for axis 0 with size 0" in error_msg:
                            QtWidgets.QMessageBox.critical(
                                self,
                                "Error de Detección",
                                "El lote no se intersecta con la ortoimagen.\n\n"
                                "Por favor, seleccione un lote que se intersecte con la ortoimagen."
                            )
                        else:
                            QtWidgets.QMessageBox.critical(
                                self,
                                "Error",
                                f"Error durante la detección: {error_msg}"
                            )
                            
            except Exception as e:
                logger.error(f"Error al verificar traslape: {str(e)}")
                QtWidgets.QMessageBox.critical(
                    self,
                    "Error",
                    f"Error al verificar traslape: {str(e)}"
                )
                return

        except Exception as e:
            logger.error(f"Error en run_segmentation: {str(e)}")
            QtWidgets.QMessageBox.critical(
                self,
                "Error",
                f"Error durante la detección: {str(e)}"
            )

